using System.Text;

namespace CqrsLens;

public static class ReportGenerator
{
    /// <summary>Makes a Mermaid-safe node id from an arbitrary name.</summary>
    public static string MermaidId(string? name) => DiagramBuilder.MermaidId(name);

    private static string LayerLegend(AnalysisResult result)
    {
        var text = "**Layer colors:** green = Domain · blue = Application · amber = Infrastructure · " +
                   "purple = Api/Web/UI · gray = Tests/other.";
        if (result.Checks.Any(c => c.Code == ArchitectureChecker.LayerViolationCode))
            text += " Red dashed edges mark `LayerViolation` findings.";
        return text;
    }

    private static string CqrsLegend(AnalysisResult result)
    {
        var text = "**Legend:** blue = command · teal = query · violet = other request · " +
                   "gray stadium = handler · amber = validator.";
        if (result.Checks.Any(c => c.Code == ArchitectureChecker.MissingHandlerCode))
            text += " Red dashed request = `MissingHandler` finding.";
        if (result.Checks.Any(c => c.Code == ArchitectureChecker.CommandWithoutValidatorCode))
            text += " Amber dashed request = `CommandWithoutValidator` finding.";
        return text;
    }

    /// <summary>Collapses user-derived text that must stay on one report line.</summary>
    internal static string InlineText(string? value)
        => (value ?? "")
            .Replace("\r\n", " ", StringComparison.Ordinal)
            .Replace('\r', ' ')
            .Replace('\n', ' ');

    /// <summary>
    /// Escapes text that Markdown must not interpret as HTML. GitHub renderers
    /// treat a raw &lt; or &gt; as markup, which silently truncates generic types
    /// such as List&lt;ProductDto&gt; in table cells.
    /// </summary>
    internal static string MarkdownText(string? value)
        => InlineText(value)
            .Replace("&", "&amp;", StringComparison.Ordinal)
            .Replace("<", "&lt;", StringComparison.Ordinal)
            .Replace(">", "&gt;", StringComparison.Ordinal);

    /// <summary>Escapes a value used in a Markdown table cell.</summary>
    internal static string TableCell(string? value)
        => MarkdownText(value).Replace("|", "\\|", StringComparison.Ordinal);

    /// <summary>Renders a Markdown code span, widening the fence when needed.</summary>
    internal static string CodeSpan(string? value)
    {
        var text = InlineText(value);
        var fence = text.Contains('`') ? "``" : "`";
        return $"{fence}{text}{fence}";
    }

    public static string Generate(AnalysisResult result)
    {
        var md = new StringBuilder();
        var rootName = new DirectoryInfo(result.RootPath).Name;

        md.AppendLine("# Architecture Report");
        md.AppendLine();
        md.AppendLine(
            $"Generated by **CqrsLens {ToolInfo.Version}** on " +
            $"{result.GeneratedAt.UtcDateTime:yyyy-MM-dd HH:mm:ss} UTC · " +
            $"{InlineText(result.ScannerName)} scanner · Source: {CodeSpan(rootName)}");
        md.AppendLine();

        // ---- Overview ------------------------------------------------------
        md.AppendLine("## Overview");
        md.AppendLine();
        md.AppendLine("| Metric | Count |");
        md.AppendLine("| --- | ---: |");
        md.AppendLine($"| Projects | {result.Projects.Count} |");
        md.AppendLine($"| Requests (commands + queries) | {result.Requests.Count} |");
        md.AppendLine($"| Handlers | {result.Handlers.Count} |");
        md.AppendLine($"| Validators | {result.Validators.Count} |");
        md.AppendLine($"| Pipeline behaviors | {result.Behaviors.Count} |");
        md.AppendLine($"| DbContexts | {result.DbContexts.Count} |");
        md.AppendLine();

        // ---- Project dependency graph --------------------------------------
        md.AppendLine("## Project Dependency Graph");
        md.AppendLine();
        var projectGraph = DiagramBuilder.ProjectGraph(result);
        if (projectGraph is null)
        {
            md.AppendLine("_No projects found._");
        }
        else
        {
            AppendDiagramOrLimitNote(md, projectGraph, "project graph");
            md.AppendLine();
            if (result.Projects
                .GroupBy(p => p.Name, StringComparer.OrdinalIgnoreCase)
                .Any(g => g.Count() > 1))
            {
                md.AppendLine("_Project references are drawn only when the target name resolves to a single " +
                              "project; ambiguous duplicate names are reported under Architecture Checks._");
                md.AppendLine();
            }
            md.AppendLine(LayerLegend(result));
        }
        md.AppendLine();

        // ---- Layers ---------------------------------------------------------
        md.AppendLine("## Layers");
        md.AppendLine();
        var layerGraph = DiagramBuilder.LayerGraph(result);
        if (layerGraph is null)
        {
            md.AppendLine("_No projects found._");
        }
        else
        {
            AppendDiagramOrLimitNote(md, layerGraph, "layer graph");
            md.AppendLine();
            md.AppendLine("_Dashed boundaries group projects into layers. Projects are grouped by Clean " +
                          "Architecture naming convention (Domain / Application / Infrastructure / Api / " +
                          "Web / UI); projects matching no convention are grouped by their top-level folder._");
        }
        md.AppendLine();

        // ---- CQRS map --------------------------------------------------------
        md.AppendLine("## CQRS Map");
        md.AppendLine();
        var cqrsSections = DiagramBuilder.CqrsMapSections(result);
        if (cqrsSections.Count == 0)
        {
            md.AppendLine("_No MediatR requests found._");
        }
        else
        {
            md.AppendLine(CqrsLegend(result));
            md.AppendLine();
            md.AppendLine("_Requests are grouped by declaring project. Handler and validator nodes are shown " +
                          "where linked and may be declared in a different project._");
            md.AppendLine();

            if (cqrsSections.Count > 1)
            {
                var projectCount = result.Requests
                    .Select(r => string.IsNullOrEmpty(r.ProjectName) ? "(unassigned)" : r.ProjectName)
                    .Distinct(StringComparer.Ordinal)
                    .Count();
                var projectText = projectCount == 1 ? "1 project" : $"{projectCount} projects";
                md.AppendLine($"_{result.Requests.Count} requests across {projectText}. " +
                              "Diagrams are split by project and balanced so each stays within GitHub's " +
                              "rendering limits; every request appears exactly once._");
                md.AppendLine();
            }

            foreach (var section in cqrsSections)
            {
                if (cqrsSections.Count > 1)
                {
                    md.AppendLine($"### {MarkdownText(section.Heading)}");
                    md.AppendLine();
                }

                if (!DiagramBuilder.IsWithinMermaidLimits(section.Source))
                {
                    md.AppendLine($"_Diagram omitted: {section.Requests.Count} requests exceed the CqrsLens " +
                                  "safety limit (45,000 characters / 400 edges). The Requests table below " +
                                  "lists every request._");
                }
                else
                {
                    AppendMermaid(md, section.Source);
                    md.AppendLine();
                    md.AppendLine($"_{MarkdownText(section.Caption)}_");
                }
                md.AppendLine();
            }

            md.AppendLine("### Requests");
            md.AppendLine();
            md.AppendLine("| Request | Type | Response | Handler | Validators | Project |");
            md.AppendLine("| --- | --- | --- | --- | --- | --- |");
            foreach (var r in result.Requests)
            {
                md.AppendLine($"| {TableCell(r.Name)} | {TableCell(r.Kind)} | {TableCell(r.ResponseType ?? "—")} | " +
                              $"{TableCell(r.Handlers.Count > 0 ? string.Join(", ", r.Handlers.Select(CSharpScanner.SimpleName)) : "—")} | " +
                              $"{TableCell(r.Validators.Count > 0 ? string.Join(", ", r.Validators.Select(CSharpScanner.SimpleName)) : "—")} | " +
                              $"{TableCell(r.ProjectName ?? "—")} |");
            }
        }
        md.AppendLine();

        // ---- Pipeline behaviors ----------------------------------------------
        md.AppendLine("## Pipeline Behaviors");
        md.AppendLine();
        if (result.Behaviors.Count == 0)
        {
            md.AppendLine("_No IPipelineBehavior implementations found._");
        }
        else
        {
            foreach (var b in result.Behaviors.OrderBy(b => b.Name, StringComparer.OrdinalIgnoreCase))
                md.AppendLine($"- {CodeSpan(b.Name)}{(b.ProjectName is null ? "" : $" — {InlineText(b.ProjectName)}")}");
        }
        md.AppendLine();

        // ---- DbContexts --------------------------------------------------------
        md.AppendLine("## Data Access (DbContexts)");
        md.AppendLine();
        if (result.DbContexts.Count == 0)
        {
            md.AppendLine("_No DbContext classes found._");
        }
        else
        {
            var orderedContexts = result.DbContexts
                .OrderBy(c => c.Name, StringComparer.OrdinalIgnoreCase)
                .ThenBy(c => c.Namespace, StringComparer.Ordinal)
                .ToList();
            var contextNameCounts = orderedContexts
                .GroupBy(c => c.Name, StringComparer.Ordinal)
                .ToDictionary(g => g.Key, g => g.Count(), StringComparer.Ordinal);

            md.AppendLine("| DbContext | Project | DbSets (property → entity) |");
            md.AppendLine("| --- | --- | --- |");
            foreach (var ctx in orderedContexts)
            {
                var sets = ctx.DbSets.Count > 0
                    ? string.Join(", ", ctx.DbSets.Select(s => $"{s.Property} → {s.Entity}"))
                    : "—";
                md.AppendLine(
                    $"| {TableCell(ctx.Name)} | {TableCell(ctx.ProjectName ?? "—")} | {TableCell(sets)} |");
            }

            foreach (var ctx in orderedContexts)
            {
                var erDiagram = DiagramBuilder.ErDiagram(ctx);
                if (erDiagram is null) continue;

                var title = contextNameCounts[ctx.Name] > 1 && !string.IsNullOrEmpty(ctx.Namespace)
                    ? $"{ctx.Namespace}.{ctx.Name}"
                    : ctx.Name;
                md.AppendLine();
                md.AppendLine($"### {MarkdownText(title)} ER Diagram");
                md.AppendLine();
                AppendDiagramOrLimitNote(md, erDiagram, $"{InlineText(title)} ER diagram");
            }
        }
        md.AppendLine();

        if (result.SkippedFiles.Count > 0)
        {
            md.AppendLine("## Scan Diagnostics");
            md.AppendLine();
            md.AppendLine($"{result.FileCount} of {result.DiscoveredFileCount} source files scanned. " +
                          $"{result.SkippedFiles.Count} skipped:");
            md.AppendLine();
            foreach (var file in result.SkippedFiles)
                md.AppendLine($"- {CodeSpan(file)}");
            md.AppendLine();
        }

        // ---- Scan diagnostics -------------------------------------------------
        md.AppendLine("## Analysis Diagnostics");
        md.AppendLine();
        AppendDiagnosticsMarkdown(md, result.Diagnostics);
        md.AppendLine();

        // ---- Architecture checks ----------------------------------------------
        md.AppendLine("## Architecture Checks");
        md.AppendLine();
        AppendChecksMarkdown(md, result.Checks, result.BaselineApplied);
        md.AppendLine();

        md.AppendLine("---");
        md.AppendLine($"_{TimingFooter(result)}_");
        md.AppendLine("_Report generated by [CqrsLens](https://github.com/AbdullahHakima/cqrslens) — static analysis only; the target solution was not built._");

        return md.ToString();
    }

    private static void AppendMermaid(StringBuilder md, string source)
    {
        md.AppendLine("```mermaid");
        md.AppendLine(source);
        md.AppendLine("```");
    }

    private static void AppendDiagramOrLimitNote(StringBuilder md, string source, string label)
    {
        if (!DiagramBuilder.IsWithinMermaidLimits(source))
        {
            md.AppendLine($"_Diagram omitted: the {label} exceeds the CqrsLens safety limit " +
                          "(45,000 characters / 400 edges)._");
            return;
        }

        AppendMermaid(md, source);
    }

    internal static void AppendDiagnosticsMarkdown(
        StringBuilder md,
        IReadOnlyList<AnalysisDiagnostic> diagnostics)
    {
        if (diagnostics.Count == 0)
        {
            md.AppendLine("No scan diagnostics.");
            return;
        }

        var errors = diagnostics.Count(d => d.Severity == AnalysisDiagnosticSeverity.Error);
        var warnings = diagnostics.Count(d => d.Severity == AnalysisDiagnosticSeverity.Warning);
        var info = diagnostics.Count - errors - warnings;
        md.AppendLine($"{errors} error(s), {warnings} warning(s), {info} info item(s):");
        md.AppendLine();

        foreach (var diagnostic in diagnostics)
        {
            var badge = diagnostic.Severity switch
            {
                AnalysisDiagnosticSeverity.Error => "❌ Error",
                AnalysisDiagnosticSeverity.Warning => "⚠️ Warning",
                _ => "ℹ️ Info",
            };
            var locality = diagnostic.Location is null
                ? ""
                : $" {CodeSpan($"{diagnostic.Location.File}:{diagnostic.Location.Line}:{diagnostic.Location.Column}")}";
            var project = string.IsNullOrEmpty(diagnostic.ProjectName)
                ? ""
                : $" ({InlineText(diagnostic.ProjectName)})";
            md.AppendLine(
                $"- {badge} **{InlineText(diagnostic.Code)}** — {InlineText(diagnostic.Message)}{locality}{project}");
        }
    }

    internal static void AppendChecksMarkdown(
        StringBuilder md,
        IReadOnlyList<CheckFinding> checks,
        bool baselineApplied = false)
    {
        if (checks.Count == 0)
        {
            md.AppendLine("All checks passed.");
            return;
        }

        var newChecks = baselineApplied
            ? checks.Where(c => !c.IsKnown).ToList()
            : checks.ToList();
        var knownChecks = baselineApplied
            ? checks.Where(c => c.IsKnown).ToList()
            : new List<CheckFinding>();

        var newErrors = newChecks.Count(c => c.Severity == CheckSeverity.Error);
        var newWarnings = newChecks.Count - newErrors;
        if (baselineApplied)
        {
            md.AppendLine(
                $"{newErrors} new error(s), {newWarnings} new warning(s); " +
                $"{knownChecks.Count} known finding(s) from the baseline:");
        }
        else
        {
            var errors = newChecks.Count(c => c.Severity == CheckSeverity.Error);
            var warnings = newChecks.Count - errors;
            md.AppendLine($"{errors} error(s), {warnings} warning(s):");
        }

        md.AppendLine();
        if (baselineApplied && newChecks.Count == 0)
        {
            md.AppendLine("No new findings.");
            md.AppendLine();
        }

        foreach (var check in newChecks)
            AppendCheckMarkdown(md, check, known: false);

        if (knownChecks.Count > 0)
        {
            md.AppendLine();
            md.AppendLine("Known (from baseline):");
            md.AppendLine();
            foreach (var check in knownChecks)
                AppendCheckMarkdown(md, check, known: true);
        }
    }

    private static void AppendCheckMarkdown(StringBuilder md, CheckFinding check, bool known)
    {
        var badge = known
            ? "ℹ️ Known"
            : check.Severity == CheckSeverity.Error ? "❌ Error" : "⚠️ Warning";
        var locality = check.Location is null
            ? ""
            : $" {CodeSpan($"{check.Location.File}:{check.Location.Line}:{check.Location.Column}")}";
        md.AppendLine(
            $"- {badge} **{InlineText(check.Code)}** — {InlineText(check.Message)}{locality}");
    }

    /// <summary>The one-line timing footer used at the end of every report.</summary>
    public static string TimingFooter(AnalysisResult result)
    {
        if (result.SkippedFiles.Count > 0)
        {
            return $"Generated by CqrsLens {ToolInfo.Version} in {result.ElapsedMilliseconds} ms — " +
                   $"{result.FileCount} of {result.DiscoveredFileCount} files scanned; " +
                   $"{result.SkippedFiles.Count} skipped.";
        }

        return $"Generated by CqrsLens {ToolInfo.Version} in {result.ElapsedMilliseconds} ms — " +
               $"{result.FileCount} files scanned.";
    }
}
