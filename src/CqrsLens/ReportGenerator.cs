using System.Text;

namespace CqrsLens;

public static class ReportGenerator
{
    /// <summary>Makes a Mermaid-safe node id from an arbitrary name.</summary>
    public static string MermaidId(string name) => DiagramBuilder.MermaidId(name);

    public static string Generate(AnalysisResult result)
    {
        var md = new StringBuilder();
        var rootName = new DirectoryInfo(result.RootPath).Name;

        md.AppendLine("# Architecture Report");
        md.AppendLine();
        md.AppendLine(
            $"Generated by **CqrsLens {ToolInfo.Version}** on " +
            $"{result.GeneratedAt.UtcDateTime:yyyy-MM-dd HH:mm:ss} UTC · " +
            $"{result.ScannerName} scanner · Source: `{rootName}`");
        md.AppendLine();

        // ---- Overview ------------------------------------------------------
        md.AppendLine("## Overview");
        md.AppendLine();
        md.AppendLine("| Metric | Count |");
        md.AppendLine("| --- | ---: |");
        md.AppendLine($"| Projects | {result.Projects.Count} |");
        md.AppendLine($"| Requests (commands + queries) | {result.Requests.Count} |");
        md.AppendLine($"| Handlers | {result.Handlers.Count} |");
        md.AppendLine($"| Validators | {result.Validators.Count} |");
        md.AppendLine($"| Pipeline behaviors | {result.Behaviors.Count} |");
        md.AppendLine($"| DbContexts | {result.DbContexts.Count} |");
        md.AppendLine();

        // ---- Project dependency graph --------------------------------------
        md.AppendLine("## Project Dependency Graph");
        md.AppendLine();
        var projectGraph = DiagramBuilder.ProjectGraph(result);
        if (projectGraph is null)
        {
            md.AppendLine("_No projects found._");
        }
        else
        {
            md.AppendLine("```mermaid");
            md.AppendLine(projectGraph);
            md.AppendLine("```");
        }
        md.AppendLine();

        // ---- Layers ---------------------------------------------------------
        md.AppendLine("## Layers");
        md.AppendLine();
        var layerGraph = DiagramBuilder.LayerGraph(result);
        if (layerGraph is null)
        {
            md.AppendLine("_No projects found._");
        }
        else
        {
            md.AppendLine("```mermaid");
            md.AppendLine(layerGraph);
            md.AppendLine("```");
            md.AppendLine();
            md.AppendLine("Projects are grouped by Clean Architecture naming convention " +
                          "(Domain / Application / Infrastructure / Api / Web / UI); " +
                          "projects matching no convention are grouped by their top-level folder.");
        }
        md.AppendLine();

        // ---- CQRS map --------------------------------------------------------
        md.AppendLine("## CQRS Map");
        md.AppendLine();
        var cqrsMap = DiagramBuilder.CqrsMap(result);
        if (cqrsMap is null)
        {
            md.AppendLine("_No MediatR requests found._");
        }
        else
        {
            md.AppendLine("```mermaid");
            md.AppendLine(cqrsMap);
            md.AppendLine("```");
            md.AppendLine();
            md.AppendLine("| Request | Type | Response | Handler | Validators | Project |");
            md.AppendLine("| --- | --- | --- | --- | --- | --- |");
            foreach (var r in result.Requests)
            {
                md.AppendLine($"| {r.Name} | {r.Kind} | {r.ResponseType ?? "—"} | " +
                              $"{(r.Handlers.Count > 0 ? string.Join(", ", r.Handlers.Select(CSharpScanner.SimpleName)) : "—")} | " +
                              $"{(r.Validators.Count > 0 ? string.Join(", ", r.Validators.Select(CSharpScanner.SimpleName)) : "—")} | " +
                              $"{r.ProjectName ?? "—"} |");
            }
        }
        md.AppendLine();

        // ---- Pipeline behaviors ----------------------------------------------
        md.AppendLine("## Pipeline Behaviors");
        md.AppendLine();
        if (result.Behaviors.Count == 0)
        {
            md.AppendLine("_No IPipelineBehavior implementations found._");
        }
        else
        {
            foreach (var b in result.Behaviors.OrderBy(b => b.Name, StringComparer.OrdinalIgnoreCase))
                md.AppendLine($"- `{b.Name}`{(b.ProjectName is null ? "" : $" — {b.ProjectName}")}");
        }
        md.AppendLine();

        // ---- DbContexts --------------------------------------------------------
        md.AppendLine("## Data Access (DbContexts)");
        md.AppendLine();
        if (result.DbContexts.Count == 0)
        {
            md.AppendLine("_No DbContext classes found._");
        }
        else
        {
            md.AppendLine("| DbContext | Project | DbSets (property → entity) |");
            md.AppendLine("| --- | --- | --- |");
            foreach (var ctx in result.DbContexts.OrderBy(c => c.Name, StringComparer.OrdinalIgnoreCase))
            {
                var sets = ctx.DbSets.Count > 0
                    ? string.Join(", ", ctx.DbSets.Select(s => $"{s.Property} → {s.Entity}"))
                    : "—";
                md.AppendLine($"| {ctx.Name} | {ctx.ProjectName ?? "—"} | {sets} |");
            }
        }
        md.AppendLine();

        if (result.SkippedFiles.Count > 0)
        {
            md.AppendLine("## Scan Diagnostics");
            md.AppendLine();
            md.AppendLine($"{result.FileCount} of {result.DiscoveredFileCount} source files scanned. " +
                          $"{result.SkippedFiles.Count} skipped:");
            md.AppendLine();
            foreach (var file in result.SkippedFiles)
                md.AppendLine($"- `{file}`");
            md.AppendLine();
        }

        // ---- Scan diagnostics -------------------------------------------------
        md.AppendLine("## Analysis Diagnostics");
        md.AppendLine();
        AppendDiagnosticsMarkdown(md, result.Diagnostics);
        md.AppendLine();

        // ---- Architecture checks ----------------------------------------------
        md.AppendLine("## Architecture Checks");
        md.AppendLine();
        AppendChecksMarkdown(md, result.Checks);
        md.AppendLine();

        md.AppendLine("---");
        md.AppendLine($"_{TimingFooter(result)}_");
        md.AppendLine("_Report generated by [CqrsLens](https://github.com/AbdullahHakima/cqrslens) — static analysis only; the target solution was not built._");

        return md.ToString();
    }

    internal static void AppendDiagnosticsMarkdown(
        StringBuilder md,
        IReadOnlyList<AnalysisDiagnostic> diagnostics)
    {
        if (diagnostics.Count == 0)
        {
            md.AppendLine("No scan diagnostics.");
            return;
        }

        var errors = diagnostics.Count(d => d.Severity == AnalysisDiagnosticSeverity.Error);
        var warnings = diagnostics.Count(d => d.Severity == AnalysisDiagnosticSeverity.Warning);
        var info = diagnostics.Count - errors - warnings;
        md.AppendLine($"{errors} error(s), {warnings} warning(s), {info} info item(s):");
        md.AppendLine();

        foreach (var diagnostic in diagnostics)
        {
            var badge = diagnostic.Severity switch
            {
                AnalysisDiagnosticSeverity.Error => "❌ Error",
                AnalysisDiagnosticSeverity.Warning => "⚠️ Warning",
                _ => "ℹ️ Info",
            };
            var locality = diagnostic.Location is null
                ? ""
                : $" `{diagnostic.Location.File}:{diagnostic.Location.Line}:{diagnostic.Location.Column}`";
            var project = string.IsNullOrEmpty(diagnostic.ProjectName)
                ? ""
                : $" ({diagnostic.ProjectName})";
            md.AppendLine(
                $"- {badge} **{diagnostic.Code}** — {diagnostic.Message}{locality}{project}");
        }
    }

    internal static void AppendChecksMarkdown(StringBuilder md, IReadOnlyList<CheckFinding> checks)
    {
        if (checks.Count == 0)
        {
            md.AppendLine("All checks passed.");
            return;
        }
        var errors = checks.Count(c => c.Severity == CheckSeverity.Error);
        var warnings = checks.Count - errors;
        md.AppendLine($"{errors} error(s), {warnings} warning(s):");
        md.AppendLine();
        foreach (var check in checks)
        {
            var badge = check.Severity == CheckSeverity.Error ? "❌ Error" : "⚠️ Warning";
            md.AppendLine($"- {badge} **{check.Code}** — {check.Message}");
        }
    }

    /// <summary>The one-line timing footer used at the end of every report.</summary>
    public static string TimingFooter(AnalysisResult result)
    {
        if (result.SkippedFiles.Count > 0)
        {
            return $"Generated by CqrsLens {ToolInfo.Version} in {result.ElapsedMilliseconds} ms — " +
                   $"{result.FileCount} of {result.DiscoveredFileCount} files scanned; " +
                   $"{result.SkippedFiles.Count} skipped.";
        }

        return $"Generated by CqrsLens {ToolInfo.Version} in {result.ElapsedMilliseconds} ms — " +
               $"{result.FileCount} files scanned.";
    }
}
