using System.Text;

namespace CqrsLens;

public static class ReportGenerator
{
    /// <summary>Makes a Mermaid-safe node id from an arbitrary name.</summary>
    public static string MermaidId(string name)
    {
        var sb = new StringBuilder();
        foreach (var c in name)
            sb.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
        var id = sb.ToString();
        if (id.Length == 0 || char.IsDigit(id[0])) id = "n_" + id;
        return id;
    }

    public static string Generate(AnalysisResult result)
    {
        var md = new StringBuilder();
        var rootName = new DirectoryInfo(result.RootPath).Name;

        md.AppendLine("# Architecture Report");
        md.AppendLine();
        md.AppendLine($"Generated by **CqrsLens 0.1.0** on {DateTime.Now:yyyy-MM-dd} · Source: `{rootName}`");
        md.AppendLine();

        // ---- Overview ------------------------------------------------------
        md.AppendLine("## Overview");
        md.AppendLine();
        md.AppendLine("| Metric | Count |");
        md.AppendLine("| --- | ---: |");
        md.AppendLine($"| Projects | {result.Projects.Count} |");
        md.AppendLine($"| Requests (commands + queries) | {result.Requests.Count} |");
        md.AppendLine($"| Handlers | {result.Handlers.Count} |");
        md.AppendLine($"| Validators | {result.Validators.Count} |");
        md.AppendLine($"| Pipeline behaviors | {result.Behaviors.Count} |");
        md.AppendLine($"| DbContexts | {result.DbContexts.Count} |");
        md.AppendLine();

        // ---- Project dependency graph --------------------------------------
        md.AppendLine("## Project Dependency Graph");
        md.AppendLine();
        if (result.Projects.Count == 0)
        {
            md.AppendLine("_No projects found._");
        }
        else
        {
            md.AppendLine("```mermaid");
            md.AppendLine("flowchart TD");
            foreach (var p in result.Projects)
                md.AppendLine($"    {MermaidId(p.Name)}[\"{p.Name}\"]");
            foreach (var p in result.Projects)
                foreach (var dep in p.ReferenceNames)
                    md.AppendLine($"    {MermaidId(p.Name)} --> {MermaidId(dep)}");
            md.AppendLine("```");
        }
        md.AppendLine();

        // ---- Layers ---------------------------------------------------------
        md.AppendLine("## Layers");
        md.AppendLine();
        if (result.Projects.Count == 0)
        {
            md.AppendLine("_No projects found._");
        }
        else
        {
            md.AppendLine("```mermaid");
            md.AppendLine("flowchart TD");
            foreach (var layer in LayerClassifier.OrderLayers(result.Projects.Select(p => p.Layer)))
            {
                md.AppendLine($"    subgraph {MermaidId("layer_" + layer)}[\"{layer}\"]");
                foreach (var p in result.Projects.Where(p => p.Layer == layer))
                    md.AppendLine($"        {MermaidId(p.Name)}[\"{p.Name}\"]");
                md.AppendLine("    end");
            }
            foreach (var p in result.Projects)
                foreach (var dep in p.ReferenceNames)
                    md.AppendLine($"    {MermaidId(p.Name)} --> {MermaidId(dep)}");
            md.AppendLine("```");
            md.AppendLine();
            md.AppendLine("Projects are grouped by Clean Architecture naming convention " +
                          "(Domain / Application / Infrastructure / Api / Web / UI); " +
                          "projects matching no convention are grouped by their top-level folder.");
        }
        md.AppendLine();

        // ---- CQRS map --------------------------------------------------------
        md.AppendLine("## CQRS Map");
        md.AppendLine();
        if (result.Requests.Count == 0)
        {
            md.AppendLine("_No MediatR requests found._");
        }
        else
        {
            md.AppendLine("```mermaid");
            md.AppendLine("flowchart LR");
            foreach (var r in result.Requests)
            {
                md.AppendLine($"    {MermaidId(r.Name)}[\"{r.Name}\"]");
                foreach (var h in r.Handlers)
                    md.AppendLine($"    {MermaidId(h)}([\"{h}\"])");
                foreach (var v in r.Validators)
                    md.AppendLine($"    {MermaidId(v)}{{\"{v}\"}}");
            }
            foreach (var r in result.Requests)
            {
                foreach (var h in r.Handlers)
                    md.AppendLine($"    {MermaidId(r.Name)} --> {MermaidId(h)}");
                foreach (var v in r.Validators)
                    md.AppendLine($"    {MermaidId(v)} -.-> {MermaidId(r.Name)}");
            }
            md.AppendLine("```");
            md.AppendLine();
            md.AppendLine("| Request | Type | Response | Handler | Validators | Project |");
            md.AppendLine("| --- | --- | --- | --- | --- | --- |");
            foreach (var r in result.Requests)
            {
                md.AppendLine($"| {r.Name} | {r.Kind} | {r.ResponseType ?? "—"} | " +
                              $"{(r.Handlers.Count > 0 ? string.Join(", ", r.Handlers) : "—")} | " +
                              $"{(r.Validators.Count > 0 ? string.Join(", ", r.Validators) : "—")} | " +
                              $"{r.ProjectName ?? "—"} |");
            }
        }
        md.AppendLine();

        // ---- Pipeline behaviors ----------------------------------------------
        md.AppendLine("## Pipeline Behaviors");
        md.AppendLine();
        if (result.Behaviors.Count == 0)
        {
            md.AppendLine("_No IPipelineBehavior implementations found._");
        }
        else
        {
            foreach (var b in result.Behaviors.OrderBy(b => b.Name, StringComparer.OrdinalIgnoreCase))
                md.AppendLine($"- `{b.Name}`{(b.ProjectName is null ? "" : $" — {b.ProjectName}")}");
        }
        md.AppendLine();

        // ---- DbContexts --------------------------------------------------------
        md.AppendLine("## Data Access (DbContexts)");
        md.AppendLine();
        if (result.DbContexts.Count == 0)
        {
            md.AppendLine("_No DbContext classes found._");
        }
        else
        {
            md.AppendLine("| DbContext | Project | DbSets (property → entity) |");
            md.AppendLine("| --- | --- | --- |");
            foreach (var ctx in result.DbContexts.OrderBy(c => c.Name, StringComparer.OrdinalIgnoreCase))
            {
                var sets = ctx.DbSets.Count > 0
                    ? string.Join(", ", ctx.DbSets.Select(s => $"{s.Property} → {s.Entity}"))
                    : "—";
                md.AppendLine($"| {ctx.Name} | {ctx.ProjectName ?? "—"} | {sets} |");
            }
        }
        md.AppendLine();
        md.AppendLine("---");
        md.AppendLine("_Report generated by [CqrsLens](https://github.com/AbdullahHakima/cqrslens) — static analysis only; the target solution was not built._");

        return md.ToString();
    }
}
