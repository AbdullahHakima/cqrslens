using System.Net;
using System.Text;

namespace CqrsLens;

/// <summary>
/// Generates a portable HTML architecture report (issue #5) with embedded CSS,
/// stat cards, and either Mermaid source blocks (loaded from a pinned,
/// SRI-checked CDN script) or pre-rendered inline SVG diagrams (zero-JS mode).
/// </summary>
public static class HtmlReportGenerator
{
    private const string MermaidVersion = "12.2.0";
    private const string MermaidIntegrity =
        "sha384-8xUhuLNMjW/cI2Dacg3DR4WliYznvIg0LVG1stctThKD/YVrJFI9TNCFxft5NYgp";

    private static string E(string? value) => WebUtility.HtmlEncode(value ?? "");

    public static string Generate(
        AnalysisResult result,
        DiagramRenderMode renderMode = DiagramRenderMode.Mermaid)
    {
        var rootName = new DirectoryInfo(result.RootPath).Name;
        var html = new StringBuilder();

        html.AppendLine("<!DOCTYPE html>");
        html.AppendLine("<html lang=\"en\">");
        html.AppendLine("<head>");
        html.AppendLine("<meta charset=\"utf-8\">");
        html.AppendLine("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">");
        html.AppendLine($"<title>Architecture Report — {E(rootName)}</title>");
        html.AppendLine("<style>");
        html.AppendLine(Css);
        html.AppendLine("</style>");
        html.AppendLine("</head>");
        html.AppendLine("<body>");
        html.AppendLine("<main>");

        html.AppendLine("<h1>Architecture Report</h1>");
        html.AppendLine(
            $"<p class=\"meta\">Generated by CqrsLens {E(ToolInfo.Version)} on " +
            $"{result.GeneratedAt.UtcDateTime:yyyy-MM-dd HH:mm:ss} UTC · " +
            $"{E(result.ScannerName)} scanner · Source: <code>{E(rootName)}</code></p>");

        if (!string.IsNullOrWhiteSpace(result.Watermark))
        {
            var stamp = ConsoleArtwork.RenderWatermarkStamp(result.Watermark, useColor: false);
            html.AppendLine($"<div class=\"watermark-overlay\" aria-hidden=\"true\">{E(result.Watermark)}</div>");
            html.AppendLine($"<pre class=\"ascii-watermark\" aria-label=\"Watermark\">{E(stamp)}</pre>");
        }

        // ---- Stat cards ------------------------------------------------------
        html.AppendLine("<section class=\"cards\">");
        AppendCard(html, "Projects", result.Projects.Count);
        AppendCard(html, "Requests", result.Requests.Count);
        AppendCard(html, "Handlers", result.Handlers.Count);
        AppendCard(html, "Validators", result.Validators.Count);
        AppendCard(html, "Pipeline behaviors", result.Behaviors.Count);
        AppendCard(html, "DbContexts", result.DbContexts.Count);
        html.AppendLine("</section>");

        // ---- Diagrams ----------------------------------------------------------
        AppendDiagram(html, "Project Dependency Graph", DiagramBuilder.ProjectGraph(result),
            "No projects found.", renderMode);
        if (result.Projects.Count > 0)
            AppendLayerLegend(html, result);
        if (result.Projects
            .GroupBy(p => p.Name, StringComparer.OrdinalIgnoreCase)
            .Any(g => g.Count() > 1))
        {
            html.AppendLine("<p class=\"note\">Project references are drawn only when the target name " +
                            "resolves to a single project; ambiguous duplicate names are reported under " +
                            "Architecture Checks.</p>");
        }

        AppendDiagram(html, "Layers", DiagramBuilder.LayerGraph(result),
            "No projects found.", renderMode);
        if (result.Projects.Count > 0)
        {
            html.AppendLine("<p class=\"note\">Dashed boundaries group projects into layers. Projects are " +
                            "grouped by Clean Architecture naming convention (Domain / Application / " +
                            "Infrastructure / Api / Web / UI); projects matching no convention are grouped by " +
                            "their top-level folder.</p>");
        }
        AppendCqrs(html, result, renderMode);
        // ---- Requests table ------------------------------------------------------
        html.AppendLine("<h2>Requests</h2>");
        if (result.Requests.Count == 0)
        {
            html.AppendLine("<p><em>No MediatR requests found.</em></p>");
        }
        else
        {
            html.AppendLine("<table>");
            html.AppendLine("<thead><tr><th>Request</th><th>Type</th><th>Response</th><th>Handler</th><th>Validators</th><th>Project</th></tr></thead>");
            html.AppendLine("<tbody>");
            foreach (var r in result.Requests)
            {
                html.AppendLine("<tr>" +
                    $"<td>{E(r.Name)}</td>" +
                    $"<td>{E(r.Kind)}</td>" +
                    $"<td>{E(r.ResponseType ?? "—")}</td>" +
                    $"<td>{E(r.Handlers.Count > 0 ? string.Join(", ", r.Handlers.Select(CSharpScanner.SimpleName)) : "—")}</td>" +
                    $"<td>{E(r.Validators.Count > 0 ? string.Join(", ", r.Validators.Select(CSharpScanner.SimpleName)) : "—")}</td>" +
                    $"<td>{E(r.ProjectName ?? "—")}</td>" +
                    "</tr>");
            }
            html.AppendLine("</tbody>");
            html.AppendLine("</table>");
        }

        // ---- Behaviors -------------------------------------------------------------
        html.AppendLine("<h2>Pipeline Behaviors</h2>");
        if (result.Behaviors.Count == 0)
        {
            html.AppendLine("<p><em>No IPipelineBehavior implementations found.</em></p>");
        }
        else
        {
            html.AppendLine("<table>");
            html.AppendLine("<thead><tr><th>Behavior</th><th>Project</th></tr></thead>");
            html.AppendLine("<tbody>");
            foreach (var b in result.Behaviors.OrderBy(b => b.Name, StringComparer.OrdinalIgnoreCase))
                html.AppendLine($"<tr><td>{E(b.Name)}</td><td>{E(b.ProjectName ?? "—")}</td></tr>");
            html.AppendLine("</tbody>");
            html.AppendLine("</table>");
        }

        // ---- Data model ----------------------------------------------------------------
        html.AppendLine("<h2>Data Access (DbContexts)</h2>");
        if (result.DbContexts.Count == 0)
        {
            html.AppendLine("<p><em>No DbContext classes found.</em></p>");
        }
        else
        {
            var orderedContexts = result.DbContexts
                .OrderBy(c => c.Name, StringComparer.OrdinalIgnoreCase)
                .ThenBy(c => c.Namespace, StringComparer.Ordinal)
                .ToList();
            var contextNameCounts = orderedContexts
                .GroupBy(c => c.Name, StringComparer.Ordinal)
                .ToDictionary(g => g.Key, g => g.Count(), StringComparer.Ordinal);

            html.AppendLine("<table>");
            html.AppendLine("<thead><tr><th>DbContext</th><th>Project</th><th>DbSets (property → entity)</th></tr></thead>");
            html.AppendLine("<tbody>");
            foreach (var ctx in orderedContexts)
            {
                var sets = ctx.DbSets.Count > 0
                    ? string.Join(", ", ctx.DbSets.Select(s => $"{s.Property} → {s.Entity}"))
                    : "—";
                html.AppendLine($"<tr><td>{E(ctx.Name)}</td><td>{E(ctx.ProjectName ?? "—")}</td><td>{E(sets)}</td></tr>");
            }
            html.AppendLine("</tbody>");
            html.AppendLine("</table>");

            foreach (var ctx in orderedContexts)
            {
                var erDiagram = DiagramBuilder.ErDiagram(ctx);
                if (erDiagram is null) continue;

                var title = contextNameCounts[ctx.Name] > 1 && !string.IsNullOrEmpty(ctx.Namespace)
                    ? $"{ctx.Namespace}.{ctx.Name}"
                    : ctx.Name;
                html.AppendLine($"<h3>{E(title)} ER Diagram</h3>");
                if (!DiagramBuilder.IsWithinMermaidLimits(erDiagram))
                {
                    html.AppendLine("<p class=\"note\"><em>Diagram omitted: the source exceeds the CqrsLens " +
                                    "safety limit (45,000 characters / 400 edges).</em></p>");
                    continue;
                }

                html.AppendLine("<figure class=\"diagram\">");
                html.AppendLine(RenderDiagram(erDiagram, renderMode));
                html.AppendLine("</figure>");
            }
        }

        if (result.SkippedFiles.Count > 0)
        {
            html.AppendLine("<h2>Scan Diagnostics</h2>");
            html.AppendLine($"<p>{result.FileCount} of {result.DiscoveredFileCount} source files scanned. " +
                            $"{result.SkippedFiles.Count} skipped:</p>");
            html.AppendLine("<ul>");
            foreach (var file in result.SkippedFiles)
                html.AppendLine($"<li><code>{E(file)}</code></li>");
            html.AppendLine("</ul>");
        }

        // ---- Analysis diagnostics ---------------------------------------------------------
        html.AppendLine("<h2>Analysis Diagnostics</h2>");
        if (result.Diagnostics.Count == 0)
        {
            html.AppendLine("<p>No scan diagnostics.</p>");
        }
        else
        {
            var diagnosticErrors = result.Diagnostics.Count(
                d => d.Severity == AnalysisDiagnosticSeverity.Error);
            var diagnosticWarnings = result.Diagnostics.Count(
                d => d.Severity == AnalysisDiagnosticSeverity.Warning);
            var diagnosticInfo = result.Diagnostics.Count - diagnosticErrors - diagnosticWarnings;
            html.AppendLine(
                $"<p>{diagnosticErrors} error(s), {diagnosticWarnings} warning(s), " +
                $"{diagnosticInfo} info item(s):</p>");
            html.AppendLine("<ul class=\"checks\">");
            foreach (var diagnostic in result.Diagnostics)
            {
                var cls = diagnostic.Severity switch
                {
                    AnalysisDiagnosticSeverity.Error => "error",
                    AnalysisDiagnosticSeverity.Warning => "warning",
                    _ => "info",
                };
                var badge = diagnostic.Severity switch
                {
                    AnalysisDiagnosticSeverity.Error => "❌ Error",
                    AnalysisDiagnosticSeverity.Warning => "⚠️ Warning",
                    _ => "ℹ️ Info",
                };
                var locality = diagnostic.Location is null
                    ? ""
                    : $" <code>{E(diagnostic.Location.File)}:{diagnostic.Location.Line}:{diagnostic.Location.Column}</code>";
                var project = string.IsNullOrEmpty(diagnostic.ProjectName)
                    ? ""
                    : $" ({E(diagnostic.ProjectName)})";
                html.AppendLine(
                    $"<li class=\"{cls}\">{badge} <strong>{E(diagnostic.Code)}</strong> — " +
                    $"{E(diagnostic.Message)}{locality}{project}</li>");
            }
            html.AppendLine("</ul>");
        }

        // ---- Checks -----------------------------------------------------------------------
        html.AppendLine("<h2>Architecture Checks</h2>");
        if (result.Checks.Count == 0)
        {
            html.AppendLine("<p>All checks passed.</p>");
        }
        else
        {
            var newChecks = result.BaselineApplied
                ? result.Checks.Where(c => !c.IsKnown).ToList()
                : result.Checks;
            var knownChecks = result.BaselineApplied
                ? result.Checks.Where(c => c.IsKnown).ToList()
                : new List<CheckFinding>();

            var errors = newChecks.Count(c => c.Severity == CheckSeverity.Error);
            var warnings = newChecks.Count - errors;
            if (result.BaselineApplied)
            {
                html.AppendLine(
                    $"<p>{errors} new error(s), {warnings} new warning(s); " +
                    $"{knownChecks.Count} known finding(s) from the baseline:</p>");
                if (newChecks.Count == 0)
                    html.AppendLine("<p>No new findings.</p>");
            }
            else
            {
                html.AppendLine($"<p>{errors} error(s), {warnings} warning(s):</p>");
            }

            html.AppendLine("<ul class=\"checks\">");
            foreach (var check in newChecks)
                AppendCheckHtml(html, check, known: false);
            foreach (var check in knownChecks)
                AppendCheckHtml(html, check, known: true);
            html.AppendLine("</ul>");
        }

        html.AppendLine("<hr>");
        html.AppendLine($"<p class=\"footer\">{E(ReportGenerator.TimingFooter(result))}<br>" +
                        "Report generated by <a href=\"https://github.com/AbdullahHakima/cqrslens\">CqrsLens</a> — " +
                        "static analysis only; the target solution was not built.</p>");

        html.AppendLine("</main>");
        if (renderMode == DiagramRenderMode.Mermaid)
        {
            html.AppendLine(
                $"<script src=\"https://cdn.jsdelivr.net/npm/mermaid@{MermaidVersion}/dist/mermaid.min.js\" " +
                $"integrity=\"{MermaidIntegrity}\" crossorigin=\"anonymous\"></script>");
            html.AppendLine("<script>");
            html.AppendLine("""
                (async () => {
                  const nodes = [...document.querySelectorAll('pre.mermaid')];
                  const showSource = (node, message) => {
                    const error = document.createElement('p');
                    error.className = 'diagram-error';
                    error.textContent = message;
                    const details = document.createElement('details');
                    const summary = document.createElement('summary');
                    summary.textContent = 'Show diagram source';
                    const pre = document.createElement('pre');
                    pre.textContent = node.textContent ?? '';
                    details.append(summary, pre);
                    node.replaceWith(error, details);
                  };
                  if (typeof mermaid === 'undefined') {
                    nodes.forEach((node) =>
                      showSource(node, 'Mermaid could not be loaded. The diagram source is shown below.'));
                    return;
                  }
                  try {
                    mermaid.initialize({
                      startOnLoad: false,
                      theme: 'default',
                      look: 'classic',
                      layout: 'elk',
                      maxTextSize: 50000,
                      maxEdges: 500,
                      securityLevel: 'strict',
                      suppressErrorRendering: true,
                      themeVariables: {
                        fontFamily: 'system-ui, -apple-system, "Segoe UI", Roboto, sans-serif'
                      }
                    });
                  } catch (error) {
                    nodes.forEach((node) =>
                      showSource(node, 'Mermaid could not be initialized. ' +
                        (error && error.message ? error.message : String(error))));
                    return;
                  }
                  for (let i = 0; i < nodes.length; i++) {
                    const node = nodes[i];
                    const source = node.textContent ?? '';
                    try {
                      const { svg } = await mermaid.render('cqrslens-diagram-' + i, source);
                      node.innerHTML = svg;
                    } catch (error) {
                      showSource(node, 'This diagram could not be rendered. ' +
                        (error && error.message ? error.message : String(error)));
                    }
                  }
                })();
                """);
            html.AppendLine("</script>");
        }
        html.AppendLine("</body>");
        html.AppendLine("</html>");

        return html.ToString();
    }

    private static void AppendCheckHtml(StringBuilder html, CheckFinding check, bool known)
    {
        var cls = known
            ? "info"
            : check.Severity == CheckSeverity.Error ? "error" : "warning";
        var badge = known
            ? "ℹ️ Known"
            : check.Severity == CheckSeverity.Error ? "❌ Error" : "⚠️ Warning";
        var locality = check.Location is null
            ? ""
            : $" <code>{E($"{check.Location.File}:{check.Location.Line}:{check.Location.Column}")}</code>";
        html.AppendLine(
            $"<li class=\"{cls}\">{badge} <strong>{E(check.Code)}</strong> — {E(check.Message)}{locality}</li>");
    }

    private static void AppendCard(StringBuilder html, string label, int value)
    {
        html.AppendLine($"<div class=\"card\"><div class=\"card-value\">{value}</div><div class=\"card-label\">{E(label)}</div></div>");
    }

    private static void AppendDiagram(
        StringBuilder html,
        string title,
        string? diagram,
        string emptyText,
        DiagramRenderMode renderMode)
    {
        html.AppendLine($"<h2>{E(title)}</h2>");
        if (diagram is null)
        {
            html.AppendLine($"<p><em>{E(emptyText)}</em></p>");
            return;
        }

        if (!DiagramBuilder.IsWithinMermaidLimits(diagram))
        {
            html.AppendLine("<p class=\"note\"><em>Diagram omitted: the source exceeds the CqrsLens " +
                            "safety limit (45,000 characters / 400 edges).</em></p>");
            return;
        }

        html.AppendLine("<figure class=\"diagram\">");
        html.AppendLine(RenderDiagram(diagram, renderMode));
        html.AppendLine("</figure>");
    }

    private static void AppendCqrs(
        StringBuilder html,
        AnalysisResult result,
        DiagramRenderMode renderMode)
    {
        html.AppendLine("<h2>CQRS Map</h2>");
        var sections = DiagramBuilder.CqrsMapSections(result);
        if (sections.Count == 0)
        {
            html.AppendLine("<p><em>No MediatR requests found.</em></p>");
            return;
        }

        AppendCqrsLegend(html, result);
        html.AppendLine("<p class=\"note\">Requests are grouped by declaring project. Handler and validator " +
                        "nodes are shown where linked and may be declared in a different project.</p>");

        if (sections.Count > 1)
        {
            var projectCount = result.Requests
                .Select(r => string.IsNullOrEmpty(r.ProjectName) ? "(unassigned)" : r.ProjectName)
                .Distinct(StringComparer.Ordinal)
                .Count();
            var projectText = projectCount == 1 ? "1 project" : $"{projectCount} projects";
            html.AppendLine($"<p class=\"note\">{result.Requests.Count} requests across {projectText}. " +
                            "Diagrams are split by project and balanced so each stays within GitHub's " +
                            "rendering limits; every request appears exactly once.</p>");
        }

        foreach (var section in sections)
        {
            if (sections.Count > 1)
                html.AppendLine($"<h3>{E(section.Heading)}</h3>");

            if (!DiagramBuilder.IsWithinMermaidLimits(section.Source))
            {
                html.AppendLine($"<p class=\"note\"><em>Diagram omitted: {section.Requests.Count} requests exceed " +
                                "the CqrsLens safety limit (45,000 characters / 400 edges). The Requests table " +
                                "below lists every request.</em></p>");
                continue;
            }

            html.AppendLine("<figure class=\"diagram\">");
            html.AppendLine(RenderDiagram(section.Source, renderMode));
            html.AppendLine($"<figcaption>{E(section.Caption)}</figcaption>");
            html.AppendLine("</figure>");
        }
    }

    private static void AppendCqrsLegend(StringBuilder html, AnalysisResult result)
    {
        html.AppendLine("<ul class=\"legend\" aria-label=\"CQRS map legend\">");
        AppendLegendItem(html, "command", "Command");
        AppendLegendItem(html, "query", "Query");
        AppendLegendItem(html, "request", "Other request");
        AppendLegendItem(html, "handler", "Handler");
        AppendLegendItem(html, "validator", "Validator");
        if (result.Checks.Any(c => c.Code == ArchitectureChecker.MissingHandlerCode))
            AppendLegendItem(html, "missing", "Missing handler");
        if (result.Checks.Any(c => c.Code == ArchitectureChecker.CommandWithoutValidatorCode))
            AppendLegendItem(html, "no-validator", "Command without validator");
        html.AppendLine("</ul>");
    }

    private static void AppendLayerLegend(StringBuilder html, AnalysisResult result)
    {
        html.AppendLine("<ul class=\"legend\" aria-label=\"Layer colors\">");
        AppendLegendItem(html, "domain", "Domain");
        AppendLegendItem(html, "application", "Application");
        AppendLegendItem(html, "infrastructure", "Infrastructure");
        AppendLegendItem(html, "api", "Api / Web / UI");
        AppendLegendItem(html, "tests", "Tests / other");
        if (result.Checks.Any(c => c.Code == ArchitectureChecker.LayerViolationCode))
            AppendLegendItem(html, "violation", "Layer violation");
        html.AppendLine("</ul>");
    }

    private static void AppendLegendItem(StringBuilder html, string swatch, string label)
        => html.AppendLine(
            $"<li><span class=\"swatch {E(swatch)}\" aria-hidden=\"true\"></span>{E(label)}</li>");

    /// <summary>
    /// RENDERING SEAM: turns a Mermaid diagram source into its HTML representation.
    /// In <see cref="DiagramRenderMode.Mermaid"/> mode this emits a
    /// <c>&lt;pre class="mermaid"&gt;</c> block rendered in the browser by Mermaid.js.
    /// In <see cref="DiagramRenderMode.Svg"/> mode this compiles the diagram to
    /// deterministic inline SVG ahead of time for zero-JS HTML reports.
    /// </summary>
    public static string RenderDiagram(
        string mermaidCode,
        DiagramRenderMode renderMode = DiagramRenderMode.Mermaid)
        => renderMode == DiagramRenderMode.Svg
            ? MermaidSvgRenderer.Render(mermaidCode)
            : $"<pre class=\"mermaid\">{E(mermaidCode)}</pre>";

