using System.Text;

namespace CqrsLens;

/// <summary>
/// Generates a token-efficient, Mermaid-free architectural context map (<c>--format agent</c>
/// and <c>--slice &lt;filter&gt;</c>) designed specifically for AI coding agents and LLMs.
/// Synthesizes project conventions ("Architectural DNA") and traces full vertical slices
/// from API Endpoint → Request(Payload) → Validator → Handler(Dependencies) → DbSet &amp; Events
/// with exact <c>File:Line</c> source pointers.
/// </summary>
public static class AgentReportGenerator
{
    public static string Generate(AnalysisResult result, string? sliceFilter = null)
    {
        ArgumentNullException.ThrowIfNull(result);

        var filter = string.IsNullOrWhiteSpace(sliceFilter) ? null : sliceFilter.Trim();
        var rootName = new DirectoryInfo(result.RootPath).Name;
        var sb = new StringBuilder();

        var handlersByFull = result.Handlers
            .GroupBy(h => h.FullName, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);
        var handlersBySimple = result.Handlers
            .GroupBy(h => h.Name, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);

        var validatorsByFull = result.Validators
            .GroupBy(v => v.FullName, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);
        var validatorsBySimple = result.Validators
            .GroupBy(v => v.Name, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);

        var notificationsByFull = result.Notifications
            .GroupBy(n => n.FullName, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);
        var notificationsBySimple = result.Notifications
            .GroupBy(n => n.Name, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);

        var notifHandlersByFull = result.NotificationHandlers
            .GroupBy(h => h.FullName, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);
        var notifHandlersBySimple = result.NotificationHandlers
            .GroupBy(h => h.Name, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);

        var endpointsByRequest = result.Endpoints
            .GroupBy(e => e.TargetRequestName, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.ToList(), StringComparer.Ordinal);

        if (filter is not null)
        {
            sb.AppendLine($"# CqrsLens Vertical Slice Trace — `{filter}` (`{rootName}`)");
            sb.AppendLine();
        }
        else
        {
            sb.AppendLine($"# CqrsLens Agent Architecture Map — `{rootName}`");
            sb.AppendLine();
            sb.AppendLine($"> Generated by CqrsLens {ToolInfo.Version} ({result.ScannerName} scanner) · " +
                          $"{result.Projects.Count} project(s), {result.Endpoints.Count} endpoint(s), " +
                          $"{result.Requests.Count} request(s), {result.Handlers.Count} handler(s), " +
                          $"{result.Validators.Count} validator(s), {result.Behaviors.Count} behavior(s), " +
                          $"{result.Notifications.Count} notification(s), {result.DbContexts.Count} DbContext(s).");
            sb.AppendLine();

            AppendArchitecturalDna(sb, result, handlersByFull, handlersBySimple);
        }

        var matchedRequests = filter is null
            ? result.Requests
            : result.Requests
                .Where(r => MatchesSlice(r, filter, handlersByFull, handlersBySimple, validatorsByFull, validatorsBySimple, endpointsByRequest))
                .ToList();

        sb.AppendLine(filter is null
            ? $"## End-to-End Vertical Slices ({matchedRequests.Count})"
            : $"## Matched Vertical Slices ({matchedRequests.Count} of {result.Requests.Count})");
        sb.AppendLine();

        if (matchedRequests.Count == 0)
        {
            sb.AppendLine(filter is null
                ? "_No CQRS requests discovered._"
                : $"_No vertical slices matched filter `{filter}`._");
            sb.AppendLine();
        }
        else
        {
            foreach (var r in matchedRequests)
            {
                var response = string.IsNullOrEmpty(r.ResponseType) ? "void" : r.ResponseType;
                sb.AppendLine($"### [{r.Kind}] `{r.Name}` → `{response}`");

                var contractLoc = FormatLoc(r.Location);
                var projLabel = string.IsNullOrEmpty(r.ProjectName) ? "" : $" [Project: `{r.ProjectName}`]";
                var markerLabel = string.IsNullOrEmpty(r.ViaMarker) ? "" : $" [Marker: `{r.ViaMarker}`]";
                sb.AppendLine($"- **Contract**: `{r.FullName}`{contractLoc}{projLabel}{markerLabel}");

                if (r.Properties.Count > 0)
                {
                    var props = string.Join(", ", r.Properties.Select(p => $"`{p.Name}: {p.Type}`"));
                    sb.AppendLine($"- **Payload**: {props}");
                }

                if (endpointsByRequest.TryGetValue(r.Name, out var eps) && eps.Count > 0)
                {
                    var epItems = eps
                        .Where(e => string.IsNullOrEmpty(e.TargetRequestNamespace) ||
                                    string.Equals(e.TargetRequestNamespace, r.Namespace, StringComparison.Ordinal))
                        .Select(e => $"`{e.DisplayLabel}` (`{e.Name}`{FormatLoc(e.Location)})")
                        .ToList();
                    if (epItems.Count == 0)
                        epItems = eps.Select(e => $"`{e.DisplayLabel}` (`{e.Name}`{FormatLoc(e.Location)})").ToList();
                    sb.AppendLine($"- **Entrypoints**: {string.Join(", ", epItems)}");
                }
                else if (r.Entrypoints.Count > 0)
                {
                    sb.AppendLine($"- **Entrypoints**: {string.Join(", ", r.Entrypoints.Select(e => $"`{e}`"))}");
                }

                if (r.Validators.Count > 0)
                {
                    var valItems = r.Validators.Select(vName =>
                    {
                        var v = Resolve(vName, validatorsByFull, validatorsBySimple);
                        return $"`{CSharpScanner.SimpleName(vName)}`{FormatLoc(v?.Location)}";
                    });
                    sb.AppendLine($"- **Validators**: {string.Join(", ", valItems)}");
                }

                if (r.Handlers.Count == 0)
                {
                    sb.AppendLine("- **Handlers**: _None (MissingHandler)_");
                }
                else
                {
                    foreach (var hName in r.Handlers)
                    {
                        var h = Resolve(hName, handlersByFull, handlersBySimple);
                        var hSimple = CSharpScanner.SimpleName(hName);
                        var hProj = !string.IsNullOrEmpty(h?.ProjectName) && h!.ProjectName != r.ProjectName
                            ? $" [Project: `{h.ProjectName}`]"
                            : "";
                        sb.AppendLine($"- **Handler**: `{hSimple}`{FormatLoc(h?.Location)}{hProj}");

                        if (h is not null)
                        {
                            if (h.Dependencies.Count > 0)
                                sb.AppendLine($"  - **Dependencies**: {string.Join(", ", h.Dependencies.Select(d => $"`{d}`"))}");
                            if (h.TouchedEntities.Count > 0)
                                sb.AppendLine($"  - **Touches DbSets**: {string.Join(", ", h.TouchedEntities.Select(e => $"`{e}`"))}");
                            if (h.PublishedNotifications.Count > 0)
                            {
                                var notifSummaries = h.PublishedNotifications.Select(nFull =>
                                {
                                    var notif = Resolve(nFull, notificationsByFull, notificationsBySimple);
                                    var nSimple = CSharpScanner.SimpleName(nFull);
                                    if (notif is null || notif.Handlers.Count == 0)
                                        return $"`{nSimple}` (no handlers)";
                                    var nhList = notif.Handlers.Select(nhName =>
                                    {
                                        var nh = Resolve(nhName, notifHandlersByFull, notifHandlersBySimple);
                                        return $"`{CSharpScanner.SimpleName(nhName)}`{FormatLoc(nh?.Location)}";
                                    });
                                    return $"`{nSimple}` → {string.Join(", ", nhList)}";
                                });
                                sb.AppendLine($"  - **Publishes Events**: {string.Join("; ", notifSummaries)}");
                            }
                            if (h.DispatchedRequests.Count > 0)
                            {
                                var dispatched = h.DispatchedRequests.Select(d => $"`{CSharpScanner.SimpleName(d)}`");
                                sb.AppendLine($"  - **Dispatches Requests**: {string.Join(", ", dispatched)}");
                            }
                        }
                    }
                }

                sb.AppendLine();
            }
        }

        // Notifications section (all in full mode, or matched in slice mode)
        var relevantNotifications = filter is null
            ? result.Notifications
            : result.Notifications
                .Where(n => n.FullName.Contains(filter, StringComparison.OrdinalIgnoreCase) ||
                            n.Handlers.Any(h => h.Contains(filter, StringComparison.OrdinalIgnoreCase)) ||
                            matchedRequests.Any(r => r.PublishedNotifications.Contains(n.FullName, StringComparer.Ordinal)))
                .ToList();

        if (relevantNotifications.Count > 0)
        {
            sb.AppendLine($"## Domain Events & Notifications ({relevantNotifications.Count})");
            sb.AppendLine();
            foreach (var n in relevantNotifications)
            {
                var nLoc = FormatLoc(n.Location);
                var handlersText = n.Handlers.Count == 0
                    ? "_No handlers_"
                    : string.Join(", ", n.Handlers.Select(hName =>
                    {
                        var nh = Resolve(hName, notifHandlersByFull, notifHandlersBySimple);
                        return $"`{CSharpScanner.SimpleName(hName)}`{FormatLoc(nh?.Location)}";
                    }));
                sb.AppendLine($"- **`{n.Name}`**{nLoc} → {handlersText}");
            }
            sb.AppendLine();
        }

        // Data Model section
        if (result.DbContexts.Count > 0)
        {
            AppendDataModelSummary(sb, result, filter, matchedRequests);
        }

        // Architecture Checks
        if (filter is null && result.Checks.Count > 0)
        {
            var activeChecks = result.BaselineApplied
                ? result.Checks.Where(c => !c.IsKnown).ToList()
                : result.Checks;
            if (activeChecks.Count > 0)
            {
                sb.AppendLine($"## Active Architecture Checks ({activeChecks.Count})");
                sb.AppendLine();
                foreach (var check in activeChecks)
                {
                    var sev = check.Severity == CheckSeverity.Error ? "ERROR" : "WARN";
                    sb.AppendLine($"- **[{sev}] `{check.Code}`**: {check.Message}{FormatLoc(check.Location)}");
                }
                sb.AppendLine();
            }
        }

        return sb.ToString();
    }

    private static void AppendArchitecturalDna(
        StringBuilder sb,
        AnalysisResult result,
        IReadOnlyDictionary<string, HandlerInfo> handlersByFull,
        IReadOnlyDictionary<string, HandlerInfo> handlersBySimple)
    {
        sb.AppendLine("## Architectural DNA & Conventions");
        sb.AppendLine();

        // 1. Layer & Project Topology
        if (result.Projects.Count > 0)
        {
            sb.AppendLine("### Layer & Project Topology");
            foreach (var p in result.Projects.OrderBy(p => p.Layer, StringComparer.Ordinal).ThenBy(p => p.Name, StringComparer.OrdinalIgnoreCase))
            {
                var refs = p.ReferenceNames.Count > 0
                    ? $" → references {string.Join(", ", p.ReferenceNames.OrderBy(r => r, StringComparer.OrdinalIgnoreCase).Select(r => $"`{r}`"))}"
                    : " (leaf project)";
                sb.AppendLine($"- **`{p.Name}`** [Layer: `{p.Layer}`]{refs}");
            }
            sb.AppendLine();
        }

        // 2. Synthesized CQRS Conventions
        sb.AppendLine("### Codebase Conventions");
        var mediatorLabel = result.Conventions.Count > 0
            ? string.Join(", ", result.Conventions)
            : "MediatR / IRequest";
        sb.AppendLine($"- **Mediator / Dispatch**: `{mediatorLabel}`");

        if (result.Requests.Count > 0)
        {
            var colocatedCount = 0;
            var linkedCount = 0;
            foreach (var r in result.Requests)
            {
                if (r.Location is null || r.Handlers.Count == 0) continue;
                var h = Resolve(r.Handlers[0], handlersByFull, handlersBySimple);
                if (h?.Location is null) continue;
                linkedCount++;
                if (string.Equals(r.Location.File, h.Location.File, StringComparison.OrdinalIgnoreCase))
                    colocatedCount++;
            }

            if (linkedCount > 0)
            {
                var layoutStyle = colocatedCount * 2 >= linkedCount
                    ? $"Co-located vertical slices ({colocatedCount}/{linkedCount} requests share a file with their handler)"
                    : $"Separate request and handler files ({linkedCount - colocatedCount}/{linkedCount} handlers in dedicated files)";
                sb.AppendLine($"- **Slice File Layout**: {layoutStyle}");
            }

            var reqProjects = result.Requests
                .Where(r => !string.IsNullOrEmpty(r.ProjectName))
                .Select(r => r.ProjectName!)
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .ToList();
            if (reqProjects.Count > 0)
                sb.AppendLine($"- **Request Contracts Live In**: {string.Join(", ", reqProjects.Select(p => $"`{p}`"))}");
        }

        if (result.Behaviors.Count > 0)
        {
            var behaviors = string.Join(", ", result.Behaviors
                .OrderBy(b => b.Name, StringComparer.OrdinalIgnoreCase)
                .Select(b => $"`{b.Name}`{FormatLoc(b.Location)}"));
            sb.AppendLine($"- **Pipeline Behaviors**: {behaviors}");
        }

        if (result.DbContexts.Count > 0)
        {
            var contexts = string.Join(", ", result.DbContexts
                .OrderBy(c => c.Name, StringComparer.OrdinalIgnoreCase)
                .Select(c => $"`{c.Name}` ({c.DbSets.Count} DbSet(s){FormatLoc(c.Location)})"));
            sb.AppendLine($"- **Data Contexts**: {contexts}");
        }

        sb.AppendLine();
    }

    private static void AppendDataModelSummary(
        StringBuilder sb,
        AnalysisResult result,
        string? filter,
        List<CqrsRequest> matchedRequests)
    {
        var touchedSet = new HashSet<string>(
            matchedRequests.SelectMany(r => r.TouchedEntities),
            StringComparer.OrdinalIgnoreCase);

        var anyOutput = false;
        var sectionSb = new StringBuilder();

        foreach (var ctx in result.DbContexts.OrderBy(c => c.Name, StringComparer.OrdinalIgnoreCase))
        {
            var relevantSets = filter is null
                ? ctx.DbSets
                : ctx.DbSets.Where(s =>
                {
                    var entitySimple = CSharpScanner.SimpleName(s.Entity);
                    var label = $"{s.Property} ({entitySimple})";
                    return touchedSet.Contains(label) ||
                           s.Property.Contains(filter, StringComparison.OrdinalIgnoreCase) ||
                           entitySimple.Contains(filter, StringComparison.OrdinalIgnoreCase);
                }).ToList();

            if (filter is not null && relevantSets.Count == 0)
                continue;

            anyOutput = true;
            sectionSb.AppendLine($"### DbContext: `{ctx.Name}`{FormatLoc(ctx.Location)}");
            if (relevantSets.Count > 0)
            {
                var setList = string.Join(", ", relevantSets.Select(s => $"`{s.Property}` → `{s.Entity}`"));
                sectionSb.AppendLine($"- **DbSets**: {setList}");
            }

            var relevantEntityNames = new HashSet<string>(
                relevantSets.Select(s => CSharpScanner.SimpleName(s.Entity)),
                StringComparer.OrdinalIgnoreCase);

            foreach (var entity in ctx.Entities.OrderBy(e => e.Name, StringComparer.OrdinalIgnoreCase))
            {
                if (filter is not null &&
                    !relevantEntityNames.Contains(entity.Name) &&
                    !entity.Name.Contains(filter, StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }

                var keys = entity.Properties.Where(p => p.IsKey).Select(p => $"`{p.Name}: {p.Type}` (PK)");
                var fks = entity.Properties.Where(p => p.IsForeignKey && !p.IsKey).Select(p => $"`{p.Name}: {p.Type}` (FK)");
                var scalars = entity.Properties.Where(p => !p.IsKey && !p.IsForeignKey && !p.IsNavigation).Select(p => $"`{p.Name}: {p.Type}`");
                var allProps = keys.Concat(fks).Concat(scalars).ToList();
                var propsText = allProps.Count > 0 ? string.Join(", ", allProps) : "_no scalar properties_";
                sectionSb.AppendLine($"- **Entity `{entity.Name}`**{FormatLoc(entity.Location)}: {propsText}");
            }

            if (filter is null && ctx.Relationships.Count > 0)
            {
                var rels = ctx.Relationships.Select(r =>
                {
                    var arrow = r.Kind switch
                    {
                        EntityRelationshipKind.OneToOne => "1:1",
                        EntityRelationshipKind.ManyToMany => "*:*",
                        _ => "1:*",
                    };
                    return $"`{CSharpScanner.SimpleName(r.PrincipalEntity)}` {arrow} `{CSharpScanner.SimpleName(r.DependentEntity)}`";
                });
                sectionSb.AppendLine($"- **Relationships**: {string.Join(", ", rels)}");
            }

            sectionSb.AppendLine();
        }

        if (anyOutput)
        {
            sb.AppendLine("## Data Model (EF Core)");
            sb.AppendLine();
            sb.Append(sectionSb);
        }
    }

    private static bool MatchesSlice(
        CqrsRequest r,
        string filter,
        IReadOnlyDictionary<string, HandlerInfo> handlersByFull,
        IReadOnlyDictionary<string, HandlerInfo> handlersBySimple,
        IReadOnlyDictionary<string, ValidatorInfo> validatorsByFull,
        IReadOnlyDictionary<string, ValidatorInfo> validatorsBySimple,
        IReadOnlyDictionary<string, List<EndpointInfo>> endpointsByRequest)
    {
        if (r.FullName.Contains(filter, StringComparison.OrdinalIgnoreCase) ||
            r.Kind.Contains(filter, StringComparison.OrdinalIgnoreCase) ||
            (r.ResponseType?.Contains(filter, StringComparison.OrdinalIgnoreCase) ?? false) ||
            (r.ProjectName?.Contains(filter, StringComparison.OrdinalIgnoreCase) ?? false) ||
            (r.Location?.File.Contains(filter, StringComparison.OrdinalIgnoreCase) ?? false))
        {
            return true;
        }

        if (r.Properties.Any(p =>
                p.Name.Contains(filter, StringComparison.OrdinalIgnoreCase) ||
                p.Type.Contains(filter, StringComparison.OrdinalIgnoreCase)))
        {
            return true;
        }

        if (r.Entrypoints.Any(e => e.Contains(filter, StringComparison.OrdinalIgnoreCase)) ||
            r.TouchedEntities.Any(e => e.Contains(filter, StringComparison.OrdinalIgnoreCase)) ||
            r.PublishedNotifications.Any(n => n.Contains(filter, StringComparison.OrdinalIgnoreCase)) ||
            r.DispatchedRequests.Any(d => d.Contains(filter, StringComparison.OrdinalIgnoreCase)))
        {
            return true;
        }

        if (endpointsByRequest.TryGetValue(r.Name, out var eps) &&
            eps.Any(e => e.Name.Contains(filter, StringComparison.OrdinalIgnoreCase) ||
                         e.Route.Contains(filter, StringComparison.OrdinalIgnoreCase)))
        {
            return true;
        }

        foreach (var hName in r.Handlers)
        {
            if (hName.Contains(filter, StringComparison.OrdinalIgnoreCase))
                return true;
            var h = Resolve(hName, handlersByFull, handlersBySimple);
            if (h is not null &&
                ((h.Location?.File.Contains(filter, StringComparison.OrdinalIgnoreCase) ?? false) ||
                 h.Dependencies.Any(d => d.Contains(filter, StringComparison.OrdinalIgnoreCase))))
            {
                return true;
            }
        }

        foreach (var vName in r.Validators)
        {
            if (vName.Contains(filter, StringComparison.OrdinalIgnoreCase))
                return true;
            var v = Resolve(vName, validatorsByFull, validatorsBySimple);
            if (v?.Location?.File.Contains(filter, StringComparison.OrdinalIgnoreCase) ?? false)
                return true;
        }

        return false;
    }

    private static T? Resolve<T>(
        string name,
        IReadOnlyDictionary<string, T> byFull,
        IReadOnlyDictionary<string, T> bySimple) where T : class
    {
        if (byFull.TryGetValue(name, out var hit))
            return hit;
        return bySimple.TryGetValue(CSharpScanner.SimpleName(name), out hit) ? hit : null;
    }

    public static string GenerateDnaAndIndex(AnalysisResult result)
    {
        ArgumentNullException.ThrowIfNull(result);

        var rootName = new DirectoryInfo(result.RootPath).Name;
        var sb = new StringBuilder();

        var handlersByFull = result.Handlers
            .GroupBy(h => h.FullName, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);
        var handlersBySimple = result.Handlers
            .GroupBy(h => h.Name, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);

        sb.AppendLine($"# CqrsLens Architectural DNA & Slice Index — `{rootName}`");
        sb.AppendLine();
        sb.AppendLine($"> {result.Projects.Count} project(s), {result.Endpoints.Count} endpoint(s), " +
                      $"{result.Requests.Count} request(s), {result.Handlers.Count} handler(s), " +
                      $"{result.Validators.Count} validator(s), {result.Behaviors.Count} behavior(s), " +
                      $"{result.Notifications.Count} notification(s), {result.DbContexts.Count} DbContext(s).");
        sb.AppendLine();

        AppendArchitecturalDna(sb, result, handlersByFull, handlersBySimple);

        sb.AppendLine($"## Vertical Slice Index ({result.Requests.Count})");
        sb.AppendLine();
        if (result.Requests.Count == 0)
        {
            sb.AppendLine("_No CQRS requests discovered._");
        }
        else
        {
            foreach (var r in result.Requests)
            {
                var response = string.IsNullOrEmpty(r.ResponseType) ? "void" : r.ResponseType;
                var ep = r.Entrypoints.Count > 0 ? $" [{string.Join(", ", r.Entrypoints)}]" : "";
                var proj = string.IsNullOrEmpty(r.ProjectName) ? "" : $" (`{r.ProjectName}`)";
                sb.AppendLine($"- **[{r.Kind}] `{r.Name}`** → `{response}`{ep}{proj}{FormatLoc(r.Location)}");
            }
        }
        sb.AppendLine();

        if (result.Notifications.Count > 0)
        {
            sb.AppendLine($"## Domain Events & Notifications Index ({result.Notifications.Count})");
            sb.AppendLine();
            foreach (var n in result.Notifications)
            {
                sb.AppendLine($"- **`{n.Name}`** ({n.Handlers.Count} handler(s)){FormatLoc(n.Location)}");
            }
            sb.AppendLine();
        }

        return sb.ToString();
    }

    public static string GenerateEntityImpact(AnalysisResult result, string entityFilter)
    {
        ArgumentNullException.ThrowIfNull(result);
        var filter = (entityFilter ?? "").Trim();
        var sb = new StringBuilder();
        var rootName = new DirectoryInfo(result.RootPath).Name;

        sb.AppendLine($"# CqrsLens Entity Impact Trace — `{filter}` (`{rootName}`)");
        sb.AppendLine();

        var handlersByFull = result.Handlers
            .GroupBy(h => h.FullName, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);
        var handlersBySimple = result.Handlers
            .GroupBy(h => h.Name, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);

        var impactedRequests = result.Requests
            .Where(r =>
                r.TouchedEntities.Any(e => e.Contains(filter, StringComparison.OrdinalIgnoreCase)) ||
                (r.ResponseType?.Contains(filter, StringComparison.OrdinalIgnoreCase) ?? false) ||
                r.Properties.Any(p => p.Type.Contains(filter, StringComparison.OrdinalIgnoreCase)) ||
                r.Handlers.Any(hName =>
                {
                    var h = Resolve(hName, handlersByFull, handlersBySimple);
                    return h is not null &&
                           (h.TouchedEntities.Any(e => e.Contains(filter, StringComparison.OrdinalIgnoreCase)) ||
                            h.Dependencies.Any(d => d.Contains(filter, StringComparison.OrdinalIgnoreCase)));
                }))
            .ToList();

        AppendDataModelSummary(sb, result, filter, impactedRequests);

        sb.AppendLine($"## Impacted Vertical Slices ({impactedRequests.Count})");
        sb.AppendLine();
        if (impactedRequests.Count == 0)
        {
            sb.AppendLine($"_No commands or queries directly touch or depend on `{filter}`._");
        }
        else
        {
            foreach (var r in impactedRequests)
            {
                var response = string.IsNullOrEmpty(r.ResponseType) ? "void" : r.ResponseType;
                var ep = r.Entrypoints.Count > 0 ? $" · Entrypoints: {string.Join(", ", r.Entrypoints.Select(e => $"`{e}`"))}" : "";
                sb.AppendLine($"- **[{r.Kind}] `{r.Name}`** → `{response}`{FormatLoc(r.Location)}{ep}");
                foreach (var hName in r.Handlers)
                {
                    var h = Resolve(hName, handlersByFull, handlersBySimple);
                    if (h is null) continue;
                    var deps = h.Dependencies.Count > 0 ? $" · Deps: {string.Join(", ", h.Dependencies.Select(d => $"`{d}`"))}" : "";
                    var sets = h.TouchedEntities.Count > 0 ? $" · DbSets: {string.Join(", ", h.TouchedEntities.Select(e => $"`{e}`"))}" : "";
                    sb.AppendLine($"  - Handler: `{h.Name}`{FormatLoc(h.Location)}{deps}{sets}");
                }
            }
        }
        sb.AppendLine();

        return sb.ToString();
    }

    public static string GenerateChecksSummary(AnalysisResult result)
    {
        ArgumentNullException.ThrowIfNull(result);
        var sb = new StringBuilder();
        var rootName = new DirectoryInfo(result.RootPath).Name;

        var activeChecks = result.BaselineApplied
            ? result.Checks.Where(c => !c.IsKnown).ToList()
            : result.Checks;
        var errors = activeChecks.Count(c => c.Severity == CheckSeverity.Error);
        var warnings = activeChecks.Count - errors;

        sb.AppendLine($"# CqrsLens Architecture Checks — `{rootName}`");
        sb.AppendLine();
        sb.AppendLine($"- **Errors**: {errors}");
        sb.AppendLine($"- **Warnings**: {warnings}");
        sb.AppendLine($"- **Scan Diagnostics**: {result.Diagnostics.Count}");
        sb.AppendLine();

        if (activeChecks.Count == 0)
        {
            sb.AppendLine("All architecture checks passed.");
        }
        else
        {
            foreach (var check in activeChecks)
            {
                var sev = check.Severity == CheckSeverity.Error ? "ERROR" : "WARN";
                sb.AppendLine($"- **[{sev}] `{check.Code}`**: {check.Message}{FormatLoc(check.Location)}");
            }
        }

        if (result.Diagnostics.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("## Scan Diagnostics");
            foreach (var d in result.Diagnostics)
                sb.AppendLine($"- **[{d.Severity}] `{d.Code}`**: {d.Message}{FormatLoc(d.Location)}");
        }

        return sb.ToString();
    }

    private static string FormatLoc(SourceLocation? loc)
        => loc is null ? "" : $" (`{loc.File}:{loc.Line}`)";
}
