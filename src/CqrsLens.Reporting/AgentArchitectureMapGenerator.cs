using System.Text;
using static CqrsLens.AgentArchitectureDnaWriter;
using static CqrsLens.AgentReportFormatter;
using static CqrsLens.AgentReportLimits;
using static CqrsLens.AgentReportLookups;
using static CqrsLens.AgentSliceMatcher;
using static CqrsLens.AgentSliceWriter;

namespace CqrsLens;

/// <summary>Builds the full agent architecture map and filtered slice traces.</summary>
internal static class AgentArchitectureMapGenerator
{
    internal static string Generate(AnalysisResult result, string? sliceFilter = null, int maxSlices = 0)
    {
        ArgumentNullException.ThrowIfNull(result);

        var filter = string.IsNullOrWhiteSpace(sliceFilter) ? null : sliceFilter.Trim();
        var rootName = new DirectoryInfo(result.RootPath).Name;
        var sb = new StringBuilder();

        var (handlersByFull, handlersBySimple) = BuildLookups(result.Handlers, h => h.FullName, h => h.Name);
        var (validatorsByFull, validatorsBySimple) = BuildLookups(result.Validators, v => v.FullName, v => v.Name);
        var (notificationsByFull, notificationsBySimple) = BuildLookups(result.Notifications, n => n.FullName, n => n.Name);
        var (notifHandlersByFull, notifHandlersBySimple) = BuildLookups(result.NotificationHandlers, h => h.FullName, h => h.Name);

        var endpointsByRequest = result.Endpoints
            .GroupBy(e => e.TargetRequestName, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.ToList(), StringComparer.Ordinal);

        if (filter is not null)
        {
            sb.AppendLine($"# CqrsLens Vertical Slice Trace — `{filter}` (`{rootName}`)");
            sb.AppendLine();
        }
        else
        {
            sb.AppendLine($"# CqrsLens Agent Architecture Map — `{rootName}`");
            sb.AppendLine();
            sb.AppendLine($"> Generated by CqrsLens {ToolInfo.Version} ({result.ScannerName} scanner) · " +
                          $"{result.Projects.Count} project(s), {result.Endpoints.Count} endpoint(s), " +
                          $"{result.Requests.Count} request(s), {result.Handlers.Count} handler(s), " +
                          $"{result.Validators.Count} validator(s), {result.Behaviors.Count} behavior(s), " +
                          $"{result.Notifications.Count} notification(s), {result.DbContexts.Count} DbContext(s).");
            sb.AppendLine();

            AppendArchitecturalDna(sb, result, handlersByFull, handlersBySimple);
        }

        var duplicateRequestNames = new HashSet<string>(
            result.Requests
                .GroupBy(r => r.Name, StringComparer.Ordinal)
                .Where(g => g.Count() > 1)
                .Select(g => g.Key),
            StringComparer.Ordinal);

        var matchedCount = 0;
        var matchedRequests = new List<CqrsRequest>();
        var genericKindFilter = false;

        if (filter is null)
        {
            matchedRequests.AddRange(result.Requests);
            matchedCount = matchedRequests.Count;
        }
        else
        {
            var hasExactName = result.Requests.Any(r =>
                string.Equals(r.Name, filter, StringComparison.OrdinalIgnoreCase));

            if (GenericKindFilters.Contains(filter) && !hasExactName)
            {
                // "Command" is a kind, not a slice. Matching it as a substring would return
                // every command in the codebase and drown the agent's context window.
                genericKindFilter = true;
            }
            else
            {
                // Exact names rank first, but related prefix/substring slices remain visible
                // (and countable) instead of being silently hidden by an exact-hit shortcut.
                var ranked = result.Requests
                    .Select(r => (Request: r, Score: ScoreSlice(r, filter, handlersByFull, handlersBySimple, validatorsByFull, validatorsBySimple, endpointsByRequest)))
                    .Where(hit => hit.Score > 0)
                    .OrderByDescending(hit => hit.Score)
                    .ThenBy(hit => hit.Request.Name, StringComparer.OrdinalIgnoreCase)
                    .ThenBy(hit => hit.Request.FullName, StringComparer.Ordinal)
                    .ToList();

                matchedCount = ranked.Count;
                var limit = maxSlices > 0 ? Math.Min(maxSlices, MaxSliceLimit) : DefaultSliceLimit;
                matchedRequests.AddRange(ranked.Take(limit).Select(hit => hit.Request));
            }
        }

        sb.AppendLine(filter is null
            ? $"## End-to-End Vertical Slices ({matchedRequests.Count})"
            : $"## Matched Vertical Slices (showing {matchedRequests.Count} of {matchedCount})");
        sb.AppendLine();

        var outputTruncated = false;
        if (matchedRequests.Count == 0)
        {
            sb.AppendLine(filter is null
                ? "_No CQRS requests discovered._"
                : genericKindFilter
                    ? $"_`{filter}` names a CQRS kind, not a slice. Search by a domain noun or exact request name (for example `CreateOrder` or `Order`)._"
                    : $"_No vertical slices matched filter `{filter}`._");
            sb.AppendLine();
        }
        else
        {
            var sliceText = new StringBuilder();
            foreach (var r in matchedRequests)
            {
                var one = new StringBuilder();
                AppendSlice(
                    one,
                    r,
                    endpointsByRequest,
                    handlersByFull,
                    handlersBySimple,
                    validatorsByFull,
                    validatorsBySimple,
                    notificationsByFull,
                    notificationsBySimple,
                    notifHandlersByFull,
                    notifHandlersBySimple,
                    allowSimpleNameEndpointFallback: !duplicateRequestNames.Contains(r.Name));

                // Keep a single trace under roughly 4k tokens even when a payload or handler
                // dependency list is unusually large. Full (unfiltered) reports are not capped.
                if (filter is not null && sliceText.Length > 0 && sliceText.Length + one.Length > MaxTraceCharacters)
                {
                    outputTruncated = true;
                    break;
                }

                sliceText.Append(one);
            }

            sb.Append(sliceText);

            var hiddenByLimit = matchedCount - matchedRequests.Count;
            if (hiddenByLimit > 0)
                sb.AppendLine($"_+{hiddenByLimit} more slice(s) matched — refine the query or raise `limit` (max {MaxSliceLimit})._");
            if (outputTruncated)
                sb.AppendLine("_Output capped to stay inside the agent context budget; narrow the query to see later slices._");
            if (hiddenByLimit > 0 || outputTruncated)
                sb.AppendLine();
        }

        // Notifications section (all in full mode, or matched in slice mode)
        var relevantNotifications = filter is null
            ? result.Notifications
            : result.Notifications
                .Where(n => n.FullName.Contains(filter, StringComparison.OrdinalIgnoreCase) ||
                            n.Handlers.Any(h => h.Contains(filter, StringComparison.OrdinalIgnoreCase)) ||
                            matchedRequests.Any(r => r.PublishedNotifications.Contains(n.FullName, StringComparer.Ordinal)))
                .ToList();

        if (relevantNotifications.Count > 0)
        {
            sb.AppendLine($"## Domain Events & Notifications ({relevantNotifications.Count})");
            sb.AppendLine();
            foreach (var n in relevantNotifications.Take(filter is null ? 50 : MaxListItems))
            {
                var nLoc = FormatLoc(n.Location);
                var handlersText = n.Handlers.Count == 0
                    ? "_No handlers_"
                    : string.Join(", ", n.Handlers.Take(5).Select(hName =>
                        FormatNotificationHandlerSummary(hName, notifHandlersByFull, notifHandlersBySimple)))
                      + (n.Handlers.Count > 5 ? $" … +{n.Handlers.Count - 5} more" : "");
                sb.AppendLine($"- **`{n.Name}`**{nLoc} → {handlersText}");
            }
            if (relevantNotifications.Count > (filter is null ? 50 : MaxListItems))
                sb.AppendLine($"- _+{relevantNotifications.Count - (filter is null ? 50 : MaxListItems)} more notification(s)._");
            sb.AppendLine();
        }

        // Data Model section
        if (result.DbContexts.Count > 0)
        {
            AppendDataModelSummary(sb, result, filter, matchedRequests);
        }

        // Architecture Checks
        if (filter is null && result.Checks.Count > 0)
        {
            var activeChecks = result.BaselineApplied
                ? result.Checks.Where(c => !c.IsKnown).ToList()
                : result.Checks;
            if (activeChecks.Count > 0)
            {
                sb.AppendLine($"## Active Architecture Checks ({activeChecks.Count})");
                sb.AppendLine();
                foreach (var check in activeChecks)
                {
                    var sev = check.Severity == CheckSeverity.Error ? "ERROR" : "WARN";
                    sb.AppendLine($"- **[{sev}] `{check.Code}`**: {check.Message}{FormatLoc(check.Location)}");
                }
                sb.AppendLine();
            }
        }

        return sb.ToString();
    }
}