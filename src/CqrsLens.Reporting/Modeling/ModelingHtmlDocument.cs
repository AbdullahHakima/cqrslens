    internal static string Render(
        string title,
        string subtitle,
        DiagramRenderMode renderMode,
        Action<StringBuilder> writeBody)
    {
        var html = new StringBuilder();
        html.AppendLine("<!DOCTYPE html>");
        html.AppendLine("<html lang=\"en\">");
        html.AppendLine("<head>");
        html.AppendLine("<meta charset=\"utf-8\">");
        html.AppendLine("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">");
        if (renderMode == DiagramRenderMode.Svg)
        {
            html.AppendLine("<meta http-equiv=\"Content-Security-Policy\" content=\"default-src 'none'; style-src 'unsafe-inline'; img-src data:;\">");
        }
        else if (renderMode == DiagramRenderMode.Interactive)
        {
            html.AppendLine("<meta http-equiv=\"Content-Security-Policy\" content=\"default-src 'none'; style-src 'unsafe-inline'; script-src 'unsafe-inline'; img-src data:;\">");
        }
        html.AppendLine($"<title>{Encode(title)}</title>");
        html.AppendLine("<style>");
        html.AppendLine(HtmlReportAssets.Css);
        html.AppendLine(ExtraCss);
        html.AppendLine("</style>");
        html.AppendLine("</head>");
        html.AppendLine("<body>");
        html.AppendLine("<main>");
        html.AppendLine($"<h1>{Encode(title)}</h1>");
        html.AppendLine($"<p class=\"meta\">{Encode(subtitle)}</p>");

        writeBody(html);

        html.AppendLine("<hr>");
        html.AppendLine("<p class=\"footer\">Generated by CqrsLens modeling engine — deterministic static analysis only.</p>");
        html.AppendLine("</main>");

        if (renderMode == DiagramRenderMode.Mermaid)
        {
            html.AppendLine(
                $"<script src=\"https://cdn.jsdelivr.net/npm/mermaid@{HtmlReportAssets.MermaidVersion}/dist/mermaid.min.js\" " +
                $"integrity=\"{HtmlReportAssets.MermaidIntegrity}\" crossorigin=\"anonymous\"></script>");
            html.AppendLine("<script>");
            html.AppendLine(HtmlReportAssets.MermaidBootstrapScript);
            html.AppendLine("</script>");
        }
        else if (renderMode == DiagramRenderMode.Interactive)
        {
            html.AppendLine("<script>");
            html.AppendLine(HtmlReportAssets.InteractiveDiagramScript);
            html.AppendLine("</script>");
        }

        html.AppendLine("</body>");
        html.AppendLine("</html>");
        return html.ToString();
    }

    internal static void AppendDiagram(
        StringBuilder html,
        string heading,
        string? mermaid,
        string emptyMessage,
        DiagramRenderMode renderMode,
        int headingLevel = 2)
    {
        html.AppendLine($"<h{headingLevel}>{Encode(heading)}</h{headingLevel}>");
        if (string.IsNullOrWhiteSpace(mermaid))
        {
            html.AppendLine($"<p><em>{Encode(emptyMessage)}</em></p>");
            return;
        }

        if (!DiagramBuilder.IsWithinMermaidLimits(mermaid))
        {
            html.AppendLine("<p class=\"note\"><em>Diagram omitted: exceeds safety limit (45,000 characters / 400 edges).</em></p>");
            return;
        }

        html.AppendLine("<figure class=\"diagram\">");
        html.AppendLine(HtmlReportGenerator.RenderDiagram(mermaid, renderMode));
        html.AppendLine("</figure>");
    }

    internal static string Badge(string status)
    {
        var cls = status.ToLowerInvariant() switch
        {
            "checks_passed" or "verified" or "matched" or "analyzed" => "badge-ok",
            "review" or "missing" or "spec_draft" or "green_incomplete" or "ambiguous" => "badge-warn",
            "conflicts" or "mismatch" or "red" or "drifted" or "invalid" or "not_found" => "badge-err",
            "not_determinable" or "inconclusive" => "badge-info",
            _ => "badge-muted",
        };
        return $"<span class=\"badge {cls}\">{Encode(status)}</span>";
    }
