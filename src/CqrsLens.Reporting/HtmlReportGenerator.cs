using System.Text;
using static CqrsLens.HtmlReportText;

namespace CqrsLens;

/// <summary>
/// Generates a portable HTML architecture report (issue #5) with embedded CSS,
/// stat cards, interactive CQRS request explorer, and either Mermaid source
/// blocks (loaded from a pinned, SRI-checked CDN script) or pre-rendered inline
/// SVG diagrams (zero-JS mode).
/// </summary>
public static class HtmlReportGenerator
{
    public static string Generate(
        AnalysisResult result,
        DiagramRenderMode renderMode = DiagramRenderMode.Mermaid)
    {
        var rootName = new DirectoryInfo(result.RootPath).Name;
        var html = new StringBuilder();

        html.AppendLine("<!DOCTYPE html>");
        html.AppendLine("<html lang=\"en\">");
        html.AppendLine("<head>");
        html.AppendLine("<meta charset=\"utf-8\">");
        html.AppendLine("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">");
        html.AppendLine($"<title>Architecture Report — {Encode(rootName)}</title>");
        html.AppendLine("<style>");
        html.AppendLine(HtmlReportAssets.Css);
        html.AppendLine("</style>");
        html.AppendLine("</head>");
        html.AppendLine("<body>");
        html.AppendLine("<main>");

        html.AppendLine("<h1>Architecture Report</h1>");
        html.AppendLine(
            $"<p class=\"meta\">Generated by CqrsLens {Encode(ToolInfo.Version)} on " +
            $"{result.GeneratedAt.UtcDateTime:yyyy-MM-dd HH:mm:ss} UTC · " +
            $"{Encode(result.ScannerName)} scanner · Source: <code>{Encode(rootName)}</code></p>");

        if (!string.IsNullOrWhiteSpace(result.Watermark))
        {
            var stamp = ConsoleArtwork.RenderWatermarkStamp(result.Watermark, useColor: false);
            html.AppendLine($"<div class=\"watermark-overlay\" aria-hidden=\"true\">{Encode(result.Watermark)}</div>");
            html.AppendLine($"<pre class=\"ascii-watermark\" aria-label=\"Watermark\">{Encode(stamp)}</pre>");
        }

        // ---- Stat cards ------------------------------------------------------
        html.AppendLine("<section class=\"cards\">");
        AppendCard(html, "Projects", result.Projects.Count);
        AppendCard(html, "Requests", result.Requests.Count);
        AppendCard(html, "Handlers", result.Handlers.Count);
        AppendCard(html, "Validators", result.Validators.Count);
        AppendCard(html, "Pipeline behaviors", result.Behaviors.Count);
        AppendCard(html, "DbContexts", result.DbContexts.Count);
        if (result.Notifications.Count > 0 || result.NotificationHandlers.Count > 0)
        {
            AppendCard(html, "Notifications", result.Notifications.Count);
            AppendCard(html, "Notification handlers", result.NotificationHandlers.Count);
        }
        html.AppendLine("</section>");

        // ---- Diagrams ----------------------------------------------------------
        HtmlDiagramSectionRenderer.Append(html, "Project Dependency Graph", DiagramBuilder.ProjectGraph(result),
            "No projects found.", renderMode);
        if (result.Projects.Count > 0)
            HtmlDiagramSectionRenderer.AppendLayerLegend(html, result);
        if (result.Projects
            .GroupBy(p => p.Name, StringComparer.OrdinalIgnoreCase)
            .Any(g => g.Count() > 1))
        {
            html.AppendLine("<p class=\"note\">Project references are drawn only when the target name " +
                            "resolves to a single project; ambiguous duplicate names are reported under " +
                            "Architecture Checks.</p>");
        }

        HtmlDiagramSectionRenderer.Append(html, "Layers", DiagramBuilder.LayerGraph(result),
            "No projects found.", renderMode);
        if (result.Projects.Count > 0)
        {
            html.AppendLine("<p class=\"note\">Dashed boundaries group projects into layers. Projects are " +
                            "grouped by Clean Architecture naming convention (Domain / Application / " +
                            "Infrastructure / Api / Web / UI); projects matching no convention are grouped by " +
                            "their top-level folder.</p>");
        }
        HtmlDiagramSectionRenderer.AppendCqrs(html, result, renderMode);

        // ---- Requests table & Interactive Explorer ------------------------------
        HtmlRequestExplorerRenderer.Render(html, result, renderMode);
        HtmlNotificationSectionRenderer.Render(html, result, renderMode);


        // ---- Behaviors -------------------------------------------------------------
        HtmlBehaviorSectionRenderer.Append(html, result);

        // ---- Data model ----------------------------------------------------------------
        HtmlDbContextSectionRenderer.Append(html, result, renderMode);

        HtmlDiagnosticsSectionRenderer.AppendScan(html, result);

        HtmlDiagnosticsSectionRenderer.AppendAnalysis(html, result);

        HtmlDiagnosticsSectionRenderer.AppendChecks(html, result);


        html.AppendLine("<hr>");
        html.AppendLine($"<p class=\"footer\">{Encode(ReportGenerator.TimingFooter(result))}<br>" +
                        "Report generated by <a href=\"https://github.com/AbdullahHakima/cqrslens\">CqrsLens</a> — " +
                        "static analysis only; the target solution was not built.</p>");

        html.AppendLine("</main>");
        if (renderMode == DiagramRenderMode.Mermaid)
        {
            html.AppendLine(
                $"<script src=\"https://cdn.jsdelivr.net/npm/mermaid@{HtmlReportAssets.MermaidVersion}/dist/mermaid.min.js\" " +
                $"integrity=\"{HtmlReportAssets.MermaidIntegrity}\" crossorigin=\"anonymous\"></script>");
            html.AppendLine("<script>");
            html.AppendLine(HtmlReportAssets.MermaidBootstrapScript);
            html.AppendLine("</script>");
        }

        html.AppendLine("</body>");
        html.AppendLine("</html>");

        return html.ToString();
    }

    private static void AppendCard(StringBuilder html, string label, int value)
    {
        html.AppendLine($"<div class=\"card\"><div class=\"card-value\">{value}</div><div class=\"card-label\">{Encode(label)}</div></div>");
    }

    /// <summary>
    /// RENDERING SEAM: turns a Mermaid diagram source into its HTML representation.
    /// In <see cref="DiagramRenderMode.Mermaid"/> mode this emits a
    /// <c>&lt;pre class="mermaid"&gt;</c> block rendered in the browser by Mermaid.js.
    /// In <see cref="DiagramRenderMode.Svg"/> mode this compiles the diagram to
    /// deterministic inline SVG ahead of time for zero-JS HTML reports.
    /// </summary>
    public static string RenderDiagram(
        string mermaidCode,
        DiagramRenderMode renderMode = DiagramRenderMode.Mermaid)
        => HtmlDiagramSectionRenderer.Render(mermaidCode, renderMode);
}