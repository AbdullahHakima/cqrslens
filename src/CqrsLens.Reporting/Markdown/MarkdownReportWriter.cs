using System.Text;

namespace CqrsLens;

/// <summary>Composes the full Markdown architecture report.</summary>
internal static class MarkdownReportWriter
{
    internal static string Generate(AnalysisResult result)
    {
        var md = new StringBuilder();

        MarkdownOverviewWriter.Write(md, result);
        MarkdownDiagramWriter.WriteProjectGraph(md, result);
        MarkdownDiagramWriter.WriteLayers(md, result);
        MarkdownCqrsWriter.Write(md, result);
        MarkdownNotificationWriter.Write(md, result);
        MarkdownBehaviorWriter.Write(md, result);
        MarkdownDbContextWriter.Write(md, result);
        MarkdownDiagnosticsWriter.WriteScanDiagnostics(md, result);
        MarkdownDiagnosticsWriter.WriteAnalysisDiagnostics(md, result);
        MarkdownChecksWriter.Write(md, result);
        WriteFooter(md, result);

        return md.ToString();
    }

    private static void WriteFooter(StringBuilder md, AnalysisResult result)
    {
        md.AppendLine("---");
        md.AppendLine($"_{TimingFooter(result)}_");
        md.AppendLine("_Report generated by [CqrsLens](https://github.com/AbdullahHakima/cqrslens) — static analysis only; the target solution was not built._");
    }

    /// <summary>The one-line timing footer used at the end of every report.</summary>
    internal static string TimingFooter(AnalysisResult result)
    {
        if (result.SkippedFiles.Count > 0)
        {
            return $"Generated by CqrsLens {ToolInfo.Version} in {result.ElapsedMilliseconds} ms — " +
                   $"{result.FileCount} of {result.DiscoveredFileCount} files scanned; " +
                   $"{result.SkippedFiles.Count} skipped.";
        }

        return $"Generated by CqrsLens {ToolInfo.Version} in {result.ElapsedMilliseconds} ms — " +
               $"{result.FileCount} files scanned.";
    }
}
