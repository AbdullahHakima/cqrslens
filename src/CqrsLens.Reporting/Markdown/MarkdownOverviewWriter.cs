using System.Text;

namespace CqrsLens;

/// <summary>Writes the report header, watermark and metric overview.</summary>
internal static class MarkdownOverviewWriter
{
    internal static void Write(StringBuilder md, AnalysisResult result)
    {
        var rootName = new DirectoryInfo(result.RootPath).Name;

        md.AppendLine("# Architecture Report");
        md.AppendLine();
        md.AppendLine(
            $"Generated by **CqrsLens {ToolInfo.Version}** on " +
            $"{result.GeneratedAt.UtcDateTime:yyyy-MM-dd HH:mm:ss} UTC · " +
            $"{MarkdownEscaping.InlineText(result.ScannerName)} scanner · Source: {MarkdownEscaping.CodeSpan(rootName)}" +
            (result.Conventions.Count > 0 ? $" · Conventions: {MarkdownEscaping.InlineText(string.Join(", ", result.Conventions))}" : ""));
        md.AppendLine();

        if (!string.IsNullOrWhiteSpace(result.Watermark))
        {
            md.AppendLine("```text");
            md.AppendLine(ConsoleArtwork.RenderWatermarkStamp(result.Watermark, useColor: false));
            md.AppendLine("```");
            md.AppendLine();
        }

        md.AppendLine("## Overview");
        md.AppendLine();
        md.AppendLine("| Metric | Count |");
        md.AppendLine("| --- | ---: |");
        md.AppendLine($"| Projects | {result.Projects.Count} |");
        md.AppendLine($"| Requests (commands + queries) | {result.Requests.Count} |");
        md.AppendLine($"| Handlers | {result.Handlers.Count} |");
        md.AppendLine($"| Validators | {result.Validators.Count} |");
        md.AppendLine($"| Pipeline behaviors | {result.Behaviors.Count} |");
        md.AppendLine($"| DbContexts | {result.DbContexts.Count} |");
        if (result.Notifications.Count > 0 || result.NotificationHandlers.Count > 0)
        {
            md.AppendLine($"| Notifications (domain events) | {result.Notifications.Count} |");
            md.AppendLine($"| Notification handlers | {result.NotificationHandlers.Count} |");
        }
        md.AppendLine();
    }
}
