using System.Text;
using static CqrsLens.HtmlReportText;

namespace CqrsLens;

/// <summary>
/// Generates a portable HTML architecture report with embedded CSS, sticky navigation,
/// stat cards, C4 System Landscape &amp; capability portal, interactive CQRS request explorer,
/// and either Mermaid source blocks or pre-rendered inline SVG diagrams (zero-JS mode).
/// </summary>
public static class HtmlReportGenerator
{
    public static string Generate(AnalysisResult result)
        => Generate(result, DiagramRenderMode.Mermaid, CqrsMapSplitMode.Count, ReportViewMode.Full, null, false);

    public static string Generate(AnalysisResult result, DiagramRenderMode renderMode)
        => Generate(result, renderMode, CqrsMapSplitMode.Count, ReportViewMode.Full, null, false);

    public static string Generate(
        AnalysisResult result,
        DiagramRenderMode renderMode,
        CqrsMapSplitMode cqrsMapSplit)
        => Generate(result, renderMode, cqrsMapSplit, ReportViewMode.Full, null, false);

    /// <summary>
    /// Generates the HTML architecture report in the requested <paramref name="viewMode"/>
    /// (<see cref="ReportViewMode.Full"/> or concise <see cref="ReportViewMode.Overview"/>),
    /// optionally focusing on a service (<paramref name="focusService"/>) and/or excluding
    /// test projects (<paramref name="excludeTests"/>).
    /// </summary>
    public static string Generate(
        AnalysisResult result,
        DiagramRenderMode renderMode = DiagramRenderMode.Mermaid,
        CqrsMapSplitMode cqrsMapSplit = CqrsMapSplitMode.Count,
        ReportViewMode viewMode = ReportViewMode.Full,
        string? focusService = null,
        bool excludeTests = false)
    {
        ArgumentNullException.ThrowIfNull(result);

        var rootName = new DirectoryInfo(result.RootPath).Name;
        var hasSystemData = SystemViewFilter.HasSystemData(result);
        var visibleEntrypoints = hasSystemData
            ? SystemViewFilter.VisibleEntrypoints(result, focusService, excludeTests)
            : new List<SystemEntrypointInfo>();
        var isZeroCqrsSystem = result.Requests.Count == 0 &&
                               result.Handlers.Count == 0 &&
                               result.Behaviors.Count == 0 &&
                               result.SystemEntrypoints.Count > 0;
        var directFlows = DirectFlowDiagramBuilder.Build(result, focusService, excludeTests);
        var directSequences = DirectSequenceBuilder.Build(result, focusService, excludeTests);
        var hasNotifications = result.Notifications.Count > 0 || result.NotificationHandlers.Count > 0;
        var html = new StringBuilder();

        html.AppendLine("<!DOCTYPE html>");
        html.AppendLine("<html lang=\"en\">");
        html.AppendLine("<head>");
        html.AppendLine("<meta charset=\"utf-8\">");
        html.AppendLine("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">");
        if (renderMode == DiagramRenderMode.Svg)
        {
            html.AppendLine("<meta http-equiv=\"Content-Security-Policy\" content=\"default-src 'none'; style-src 'unsafe-inline'; img-src data:;\">");
        }
        html.AppendLine($"<title>Architecture Report — {Encode(rootName)}</title>");
        html.AppendLine("<style>");
        html.AppendLine(HtmlReportAssets.Css);
        html.AppendLine("</style>");
        html.AppendLine("</head>");
        html.AppendLine("<body>");
        html.AppendLine("<div class=\"portal-shell\">");

        AppendNavigation(
            html,
            viewMode,
            hasSystemData,
            visibleEntrypoints.Count > 0,
            isZeroCqrsSystem,
            directFlows.Count > 0,
            directSequences.Count > 0,
            hasNotifications);

        html.AppendLine("<main>");
        html.AppendLine("<h1>Architecture Report</h1>");
        html.AppendLine(
            $"<p class=\"meta\">Generated by CqrsLens {Encode(ToolInfo.Version)} on " +
            $"{result.GeneratedAt.UtcDateTime:yyyy-MM-dd HH:mm:ss} UTC · " +
            $"{Encode(result.ScannerName)} scanner · Source: <code>{Encode(rootName)}</code></p>");

        if (result.ArchitectureStyles.Count > 0)
        {
            html.AppendLine("<div class=\"tech-badges\" aria-label=\"Architecture styles\">");
            html.Append("<span class=\"meta\"><strong>Architecture styles:</strong></span>");
            foreach (var style in result.ArchitectureStyles)
                html.Append($"<span class=\"tech-badge\">{Encode(style)}</span>");
            html.AppendLine("</div>");
        }

        if (!string.IsNullOrWhiteSpace(result.Watermark))
        {
            var stamp = ConsoleArtwork.RenderWatermarkStamp(result.Watermark, useColor: false);
            html.AppendLine($"<div class=\"watermark-overlay\" aria-hidden=\"true\">{Encode(result.Watermark)}</div>");
            html.AppendLine($"<pre class=\"ascii-watermark\" aria-label=\"Watermark\">{Encode(stamp)}</pre>");
        }

        // ---- Stat cards ------------------------------------------------------
        var checkErrors = result.Checks.Count(c => !c.IsKnown && c.Severity == CheckSeverity.Error);
        var checkWarnings = result.Checks.Count(c => !c.IsKnown && c.Severity == CheckSeverity.Warning);

        var hasNonEfStores = result.DataStores.Count > result.DbContexts.Count ||
            result.DataStores.Any(d => d.Kind is not DataStoreKind.EfCore and not DataStoreKind.Ef6);

        html.AppendLine("<section id=\"overview\" class=\"cards\">");
        AppendCard(html, "Projects", result.Projects.Count);
        if (isZeroCqrsSystem)
        {
            AppendCard(html, "System entrypoints", result.SystemEntrypoints.Count);
            AppendCard(html, "Integration flows", result.IntegrationFlows.Count);
            if (result.Validators.Count > 0)
                AppendCard(html, "Validators", result.Validators.Count);
            if (result.DbContexts.Count == 0 && result.DataStores.Count > 0)
            {
                AppendCard(html, "Data stores", result.DataStores.Count);
            }
            else
            {
                AppendCard(html, "DbContexts", result.DbContexts.Count);
                if (hasNonEfStores)
                    AppendCard(html, "Data stores", result.DataStores.Count);
            }
            if (hasNotifications)
            {
                AppendCard(html, "Notifications (domain events)", result.Notifications.Count);
                AppendCard(html, "Notification handlers", result.NotificationHandlers.Count);
            }
        }
        else
        {
            AppendCard(html, "Requests (commands + queries)", result.Requests.Count);
            AppendCard(html, "Handlers", result.Handlers.Count);
            AppendCard(html, "Validators", result.Validators.Count);
            AppendCard(html, "Pipeline behaviors", result.Behaviors.Count);
            AppendCard(html, "DbContexts", result.DbContexts.Count);
            if (hasNonEfStores)
                AppendCard(html, "Data stores", result.DataStores.Count);
            if (hasNotifications)
            {
                AppendCard(html, "Notifications (domain events)", result.Notifications.Count);
                AppendCard(html, "Notification handlers", result.NotificationHandlers.Count);
            }
            if (result.SystemEntrypoints.Count > 0 || result.IntegrationFlows.Count > 0)
            {
                AppendCard(html, "System entrypoints", result.SystemEntrypoints.Count);
                AppendCard(html, "Integration flows", result.IntegrationFlows.Count);
            }
        }
        AppendCard(html, "Architecture checks", $"{checkErrors} error(s), {checkWarnings} warning(s)");
        html.AppendLine("</section>");

        if (viewMode == ReportViewMode.Overview)
        {
            SystemOverviewHtmlRenderer.Append(
                html, result, renderMode, focusService, excludeTests, entrypointsAnchorId: "entrypoints");

            if (isZeroCqrsSystem)
            {
                HtmlDirectSectionRenderer.AppendFlows(html, directFlows, renderMode);
                HtmlDirectSectionRenderer.AppendSequences(html, directSequences, renderMode, "Operation Sequences");
            }

            html.AppendLine("<section id=\"checks\">");
            html.AppendLine("<details class=\"portal-section\" open>");
            html.AppendLine($"<summary class=\"portal-summary\">Architecture Checks Summary ({checkErrors} error(s), {checkWarnings} warning(s))</summary>");
            html.AppendLine("<div class=\"portal-body\">");
            HtmlDiagnosticsSectionRenderer.AppendChecksSummary(html, result);
            html.AppendLine("</div>");
            html.AppendLine("</details>");
            html.AppendLine("</section>");
        }
        else
        {
            SystemOverviewHtmlRenderer.Append(
                html, result, renderMode, focusService, excludeTests, entrypointsAnchorId: "system-entrypoints");

            HtmlConfigurationSectionRenderer.Append(html, result);

            // ---- Architecture Graphs & Flow ----------------------------------
            html.AppendLine("<section id=\"architecture-graphs\">");
            html.AppendLine("<details class=\"portal-section\" open>");
            html.AppendLine(isZeroCqrsSystem
                ? "<summary class=\"portal-summary\">Project Dependency Graph &amp; Layers</summary>"
                : "<summary class=\"portal-summary\">Project Dependency Graph, Layers &amp; Flow</summary>");
            html.AppendLine("<div class=\"portal-body\">");

            var projectGraph = excludeTests || !string.IsNullOrWhiteSpace(focusService)
                ? DiagramBuilder.ProjectGraph(result, excludeTests, focusService)
                : DiagramBuilder.ProjectGraph(result);
            HtmlDiagramSectionRenderer.Append(html, "Project Dependency Graph", projectGraph,
                "No projects found.", renderMode);
            if (result.Projects.Count > 0)
                HtmlDiagramSectionRenderer.AppendLayerLegend(html, result);
            if (result.Projects
                .GroupBy(p => p.Name, StringComparer.OrdinalIgnoreCase)
                .Any(g => g.Count() > 1))
            {
                html.AppendLine("<p class=\"note\">Project references are drawn only when the target name " +
                                "resolves to a single project; ambiguous duplicate names are reported under " +
                                "Architecture Checks.</p>");
            }

            var layerGraph = excludeTests || !string.IsNullOrWhiteSpace(focusService)
                ? DiagramBuilder.LayerGraph(result, excludeTests, focusService)
                : DiagramBuilder.LayerGraph(result);
            HtmlDiagramSectionRenderer.Append(html, "Layers", layerGraph,
                "No projects found.", renderMode);
            if (result.Projects.Count > 0)
            {
                html.AppendLine("<p class=\"note\">Dashed boundaries group projects into layers. Projects are " +
                                "grouped by Clean Architecture naming convention (Domain / Application / " +
                                "Infrastructure / Api / Web / UI); projects matching no convention are grouped by " +
                                "their top-level folder.</p>");
            }
            if (!isZeroCqrsSystem)
                HtmlDiagramSectionRenderer.AppendFlow(html, result, renderMode);

            html.AppendLine("</div>");
            html.AppendLine("</details>");
            html.AppendLine("</section>");

            if (isZeroCqrsSystem)
            {
                HtmlDirectSectionRenderer.AppendFlows(html, directFlows, renderMode);
                HtmlDirectSectionRenderer.AppendSequences(html, directSequences, renderMode, "Operation Sequences");

                if (hasNotifications)
                {
                    html.AppendLine("<section id=\"notifications\">");
                    html.AppendLine("<details class=\"portal-section\">");
                    html.AppendLine($"<summary class=\"portal-summary\">Domain Events &amp; Notifications ({result.Notifications.Count})</summary>");
                    html.AppendLine("<div class=\"portal-body\">");
                    HtmlNotificationSectionRenderer.Render(html, result, renderMode);
                    html.AppendLine("</div>");
                    html.AppendLine("</details>");
                    html.AppendLine("</section>");
                }
            }
            else
            {
                HtmlDirectSectionRenderer.AppendFlows(html, directFlows, renderMode);
                HtmlDirectSectionRenderer.AppendSequences(html, directSequences, renderMode, "Direct Operation Sequences");

                // ---- Entrypoints --------------------------------------------------
                html.AppendLine("<section id=\"entrypoints\">");
                HtmlEndpointSectionRenderer.Append(html, result);
                html.AppendLine("</section>");

                // ---- CQRS & Vertical Slices --------------------------------------
                html.AppendLine("<section id=\"cqrs-slices\">");
                html.AppendLine("<details class=\"portal-section\" open>");
                html.AppendLine("<summary class=\"portal-summary\">CQRS Map, Validation Coverage &amp; Request Explorer</summary>");
                html.AppendLine("<div class=\"portal-body\">");
                HtmlDiagramSectionRenderer.AppendCqrs(html, result, renderMode, cqrsMapSplit);
                HtmlValidationCoverageSectionRenderer.Append(html, result);

                var seqHtml = new StringBuilder();
                HtmlSequenceSectionRenderer.Append(seqHtml, result, renderMode);
                if (seqHtml.Length > 0)
                {
                    html.AppendLine("<details class=\"portal-section\">");
                    html.AppendLine("<summary class=\"portal-summary\">Request Sequences (per-request diagrams)</summary>");
                    html.AppendLine("<div class=\"portal-body\">");
                    html.Append(seqHtml);
                    html.AppendLine("</div>");
                    html.AppendLine("</details>");
                }

                HtmlRequestExplorerRenderer.Render(html, result, renderMode);
                HtmlNotificationSectionRenderer.Render(html, result, renderMode);
                HtmlBehaviorSectionRenderer.Append(html, result, renderMode);
                html.AppendLine("</div>");
                html.AppendLine("</details>");
                html.AppendLine("</section>");
            }

            // ---- Data model ---------------------------------------------------
            html.AppendLine("<section id=\"data-model\">");
            html.AppendLine("<details class=\"portal-section\">");
            html.AppendLine($"<summary class=\"portal-summary\">Data Model &amp; ER Diagrams ({result.DbContexts.Count} DbContext(s))</summary>");
            html.AppendLine("<div class=\"portal-body\">");
            HtmlDbContextSectionRenderer.Append(html, result, renderMode);
            html.AppendLine("</div>");
            html.AppendLine("</details>");
            html.AppendLine("</section>");

            // ---- Diagnostics & Checks -----------------------------------------
            html.AppendLine("<section id=\"checks\">");
            html.AppendLine("<details class=\"portal-section\">");
            html.AppendLine($"<summary class=\"portal-summary\">Diagnostics &amp; Architecture Checks ({checkErrors} error(s), {checkWarnings} warning(s))</summary>");
            html.AppendLine("<div class=\"portal-body\">");
            HtmlDiagnosticsSectionRenderer.AppendScan(html, result);
            HtmlDiagnosticsSectionRenderer.AppendAnalysis(html, result);
            HtmlDiagnosticsSectionRenderer.AppendChecks(html, result);
            html.AppendLine("</div>");
            html.AppendLine("</details>");
            html.AppendLine("</section>");
        }

        html.AppendLine("<hr>");
        html.AppendLine($"<p class=\"footer\">{Encode(ReportGenerator.TimingFooter(result))}<br>" +
                        "Report generated by <a href=\"https://github.com/AbdullahHakima/cqrslens\">CqrsLens</a> — " +
                        "static analysis only; the target solution was not built.</p>");

        html.AppendLine("</main>");
        html.AppendLine("</div>");

        if (renderMode == DiagramRenderMode.Mermaid)
        {
            html.AppendLine(
                $"<script src=\"https://cdn.jsdelivr.net/npm/mermaid@{HtmlReportAssets.MermaidVersion}/dist/mermaid.min.js\" " +
                $"integrity=\"{HtmlReportAssets.MermaidIntegrity}\" crossorigin=\"anonymous\"></script>");
            html.AppendLine("<script>");
            html.AppendLine(HtmlReportAssets.MermaidBootstrapScript);
            html.AppendLine("</script>");
        }

        html.AppendLine("</body>");
        html.AppendLine("</html>");

        return html.ToString();
    }

    private static void AppendNavigation(
        StringBuilder html,
        ReportViewMode viewMode,
        bool hasSystemData,
        bool hasVisibleEntrypoints,
        bool isZeroCqrsSystem,
        bool hasDirectFlows,
        bool hasDirectSequences,
        bool hasNotifications)
    {
        html.AppendLine("<nav class=\"toc\" aria-label=\"Report navigation\">");
        html.AppendLine("<div class=\"toc-title\">Report Sections</div>");
        html.AppendLine("<ul>");
        html.AppendLine("<li><a href=\"#overview\">Overview</a></li>");
        if (hasSystemData)
            html.AppendLine("<li><a href=\"#system-at-a-glance\">System at a Glance</a></li>");
        if (viewMode == ReportViewMode.Overview)
        {
            if (hasVisibleEntrypoints)
                html.AppendLine("<li><a href=\"#entrypoints\">Entrypoints</a></li>");
            if (isZeroCqrsSystem && hasDirectFlows)
                html.AppendLine("<li><a href=\"#direct-flows\">Direct Flows</a></li>");
            if (isZeroCqrsSystem && hasDirectSequences)
                html.AppendLine("<li><a href=\"#operation-sequences\">Operation Sequences</a></li>");
            html.AppendLine("<li><a href=\"#checks\">Architecture Checks</a></li>");
        }
        else if (isZeroCqrsSystem)
        {
            html.AppendLine("<li><a href=\"#architecture-graphs\">Architecture Graphs</a></li>");
            if (hasDirectFlows)
                html.AppendLine("<li><a href=\"#direct-flows\">Direct Flows</a></li>");
            if (hasDirectSequences)
                html.AppendLine("<li><a href=\"#operation-sequences\">Operation Sequences</a></li>");
            if (hasNotifications)
                html.AppendLine("<li><a href=\"#notifications\">Domain Events</a></li>");
            html.AppendLine("<li><a href=\"#data-model\">Data Model</a></li>");
            html.AppendLine("<li><a href=\"#checks\">Diagnostics &amp; Checks</a></li>");
        }
        else
        {
            html.AppendLine("<li><a href=\"#architecture-graphs\">Architecture Graphs</a></li>");
            if (hasDirectFlows)
                html.AppendLine("<li><a href=\"#direct-flows\">Direct Flows</a></li>");
            if (hasDirectSequences)
                html.AppendLine("<li><a href=\"#operation-sequences\">Direct Sequences</a></li>");
            html.AppendLine("<li><a href=\"#entrypoints\">Entrypoints</a></li>");
            html.AppendLine("<li><a href=\"#cqrs-slices\">CQRS &amp; Slices</a></li>");
            html.AppendLine("<li><a href=\"#data-model\">Data Model</a></li>");
            html.AppendLine("<li><a href=\"#checks\">Diagnostics &amp; Checks</a></li>");
        }
        html.AppendLine("</ul>");
        html.AppendLine("</nav>");
    }

    private static void AppendCard(StringBuilder html, string label, int value)
    {
        html.AppendLine($"<div class=\"card\"><div class=\"card-value\">{value}</div><div class=\"card-label\">{Encode(label)}</div></div>");
    }

    private static void AppendCard(StringBuilder html, string label, string value)
    {
        html.AppendLine($"<div class=\"card\"><div class=\"card-value\">{Encode(value)}</div><div class=\"card-label\">{Encode(label)}</div></div>");
    }

    /// <summary>
    /// RENDERING SEAM: turns a Mermaid diagram source into its HTML representation.
    /// In <see cref="DiagramRenderMode.Mermaid"/> mode this emits a
    /// <c>&lt;pre class="mermaid"&gt;</c> block rendered in the browser by Mermaid.js.
    /// In <see cref="DiagramRenderMode.Svg"/> mode this compiles the diagram to
    /// deterministic inline SVG ahead of time for zero-JS HTML reports.
    /// </summary>
    public static string RenderDiagram(
        string mermaidCode,
        DiagramRenderMode renderMode = DiagramRenderMode.Mermaid)
        => HtmlDiagramSectionRenderer.Render(mermaidCode, renderMode);
}
