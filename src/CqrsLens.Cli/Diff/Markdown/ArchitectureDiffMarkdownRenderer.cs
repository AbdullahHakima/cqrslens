using System.Text;

using static CqrsLens.JsonReportGenerator;

namespace CqrsLens;

/// <summary>Renders an architecture diff as the Markdown report used in pull requests and CI summaries.</summary>
internal static class ArchitectureDiffMarkdownRenderer
{
    internal static string Generate(
        ArchitectureDiff diff,
        AnalysisResult? headResult = null,
        string? ciRoot = null)
    {
        ArgumentNullException.ThrowIfNull(diff);

        var markdown = new StringBuilder();
        markdown.AppendLine(ArchitectureDiffer.CommentMarker);
        markdown.AppendLine("## CqrsLens Architecture Diff");
        markdown.AppendLine();

        var timestamp = DateTimeOffset.TryParse(diff.GeneratedAt, out var generatedAt)
            ? $"{generatedAt.UtcDateTime:yyyy-MM-dd HH:mm:ss} UTC"
            : ReportGenerator.InlineText(diff.GeneratedAt);

        var rootComparison =
            string.Equals(diff.BaseRootName, diff.HeadRootName, StringComparison.Ordinal) ||
            string.IsNullOrEmpty(diff.BaseRootName)
                ? ReportGenerator.CodeSpan(string.IsNullOrEmpty(diff.HeadRootName) ? "." : diff.HeadRootName)
                : $"{ReportGenerator.CodeSpan(diff.BaseRootName)} → {ReportGenerator.CodeSpan(diff.HeadRootName)}";

        markdown.AppendLine(
            $"Compared {rootComparison} with **CqrsLens {ToolInfo.Version}** " +
            $"({ReportGenerator.InlineText(diff.Scanner)} scanner) on {timestamp}.");
        markdown.AppendLine();

        WriteWatermark(markdown, diff.Watermark);

        if (diff.HasChanges)
        {
            markdown.AppendLine(DiffHeadlineBuilder.Build(diff));
            markdown.AppendLine();
        }
        else
        {
            markdown.AppendLine("✅ **No architecture changes detected** between the base scan and this revision.");
            markdown.AppendLine();
        }

        DiffSummaryTableWriter.Write(markdown, diff.Summary);
        DiffChecksSectionWriter.Write(markdown, diff, headResult, ciRoot);
        DiffCqrsSurfaceSectionWriter.Write(markdown, diff);
        DiffProjectsSectionWriter.Write(markdown, diff.Projects);
        DiffDbContextsSectionWriter.Write(markdown, diff.DbContexts);

        markdown.AppendLine("---");
        markdown.AppendLine($"_Diff generated by [CqrsLens](https://github.com/AbdullahHakima/cqrslens) {ToolInfo.Version}._");

        return markdown.ToString();
    }

    private static void WriteWatermark(StringBuilder markdown, string? watermark)
    {
        if (string.IsNullOrWhiteSpace(watermark))
            return;

        markdown.AppendLine("```text");
        markdown.AppendLine(ConsoleArtwork.RenderWatermarkStamp(watermark, useColor: false));
        markdown.AppendLine("```");
        markdown.AppendLine();
    }
}
